// POST /api/attendance/start —— 发起签到
// body: { deadlineMinutes?: number } 默认 30，范围 1~1440
// ------------------------------------------------------------
router.post('/attendance/start', async (req, res, next) => {
  try {
    const me = req.session.user;
    // 班长无权限发起签到（由教师/管理员发起）
    if (me.role === 'monitor') {
      return res.status(403).json({ error: '无权限：班长不能发起签到' });
    }
    const minutes = Math.min(Math.max(Number(req.body.deadlineMinutes) || 30, 1), 1440);
    // 发起范围（方案 A）：
    //   · 教师/班主任 → 只对本班发起（class_id = 该账号班级）；只关闭**本班**上一场（不再关别人的场次）
    //   · 管理员       → 校级发起：为每个有在读学生的班级各建一场（"全校签到"按班拆分）
    let targetClassIds = [];
    if (me.role === 'admin') {
      // 管理员：显式指定班级 → 只为该班发起（签到操作台「查看班级」选中某班时用）；
      //         未指定 / classId=all → 校级发起：为每个有在读学生的班级各建一场
      const reqCidRaw = req.body.classId === undefined || req.body.classId === null ? '' : String(req.body.classId).trim();
      const reqCid = Number(reqCidRaw);
      if (reqCidRaw !== '' && reqCidRaw !== 'all' && reqCidRaw !== '0' && Number.isInteger(reqCid) && reqCid > 0) {
        const c = await pool.query('SELECT id FROM classes WHERE id = $1', [reqCid]);
        if (c.rowCount === 0) return res.status(400).json({ error: '班级参数无效' });
        targetClassIds = [reqCid];
      } else {
        const c = await pool.query(
          `SELECT DISTINCT class_id AS id FROM students
            WHERE is_active = true AND status = '在读' AND class_id IS NOT NULL ORDER BY 1`
        );
        targetClassIds = c.rows.map((r) => r.id);
        if (targetClassIds.length === 0) return res.status(400).json({ error: '没有在读学生的班级，无法发起签到' });
      }
    } else {
      const mine = await viewerClassIds(me);       // 教师所带班级（含班主任/任课）
      const reqCid = Number(req.body.classId);
      if (Number.isInteger(reqCid) && reqCid > 0) {
        if (!mine.includes(reqCid)) return res.status(403).json({ error: '无权限：只能对自己所带班级发起签到' });
        targetClassIds = [reqCid];
      } else {
        if (!mine.length) return res.status(400).json({ error: '当前账号未绑定班级，无法发起签到' });
        targetClassIds = [mine[0]];                 // 主班级（卡片/座位表就是它）
      }
    }

    const created = [];
    const appliedTotal = { inserted: 0, updated: 0 };
    const closedPreviousIds = [];
    for (const cid of targetClassIds) {
      // 该班若有进行中的场次：先补缺勤并关闭（同班新旧不并存；别的班的场次不动）
      //   v35 例外：**每天自动签到（早/晚）场次不被手动发起顶掉**（它是不限时的台账场次，
      //   手动发起只新增一场，老流程按"最新 active"继续工作；自动场次由次日 0 点统一收口）
      const active = await activeSessionFor(cid);
      if (active && active.class_id === cid && !active.auto_generated) {
        await finalizeAbsent(active.id);
        await pool.query(`UPDATE attendance_sessions SET status = 'closed' WHERE id = $1`, [active.id]);
        closedPreviousIds.push(active.id);
      } else if (active && active.class_id === null && !active.auto_generated) {
        // 进行中的是"全校场次"：不再重复建（该场次已覆盖本班）
        created.push({
          id: active.id, classId: cid, shared: true,
          startTime: active.start_time, deadline: active.deadline, status: active.status,
          createdBy: active.created_by, createdByName: active.created_by_name, createdByRole: active.created_by_role,
          startSource: active.start_source, deadlineMinutes: active.deadline_minutes,
        });
        continue;
      }
      // 记录发起人（created_by*）与来源（start_source='manual'）+ 归属班级（class_id）
      const { rows } = await pool.query(
        `INSERT INTO attendance_sessions
           (start_time, deadline, status, created_by, created_by_name, created_by_role, start_source, deadline_minutes, class_id)
         VALUES (now(), now() + make_interval(mins => $1::int), 'active', $2, $3, $4, 'manual', $1::int, $5)
         RETURNING id, start_time, deadline, status, created_by, created_by_name, created_by_role, start_source, deadline_minutes, class_id`,
        [minutes, me.id, me.displayName || me.username, me.role, cid]
      );
      const s = rows[0];
      // 当天登记过「全天请假」的学生，直接在本场次记为请假（无需再签到）
      const applied = await applyDayLeaves(s.id);
      appliedTotal.inserted += applied.inserted;
      appliedTotal.updated += applied.updated;
      created.push({
        id: s.id, classId: cid, shared: false,
        startTime: s.start_time, deadline: s.deadline, status: s.status,
        createdBy: s.created_by, createdByName: s.created_by_name, createdByRole: s.created_by_role,
        startSource: s.start_source, deadlineMinutes: s.deadline_minutes,
      });
    }
    // 操作日志：谁在什么时间以多长截止时长发起了哪些场次（可追溯）
    //   sessionId / closedPreviousSessionId 为"代表场次"（兼容旧日志查询）；
    //   sessionIds / closedPreviousSessionIds 为完整列表（方案 A：全校发起会按班拆成多场）
    const createdIds = created.filter((x) => !x.shared).map((x) => x.id);
    await logOperation(req, 'session_start', {
      sessionId: (created[0] && created[0].id) || null,
      sessionIds: createdIds,
      classIds: targetClassIds,
      startSource: 'manual',
      deadlineMinutes: minutes,
      closedPreviousSessionId: closedPreviousIds[0] || null,
      closedPreviousSessionIds: closedPreviousIds,
      dayLeaveApplied: appliedTotal.inserted + appliedTotal.updated,
    });
    const first = created[0] || null;
    res.status(201).json({
      session: first,
      sessions: created,
      createdCount: created.filter((x) => !x.shared).length,
      sharedCount: created.filter((x) => x.shared).length,
      classIds: targetClassIds,
    });
  } catch (err) {
    next(err);
  }
});

// ------------------------------------------------------------
// POST /api/attendance/checkin —— 签到操作
// body: { studentId, action: 'present' | 'leave' | 'cancel', leaveReason? }
//  - 签到窗口：截止时间（deadline）后拒绝签到，返回"签到窗口已关闭"
//  - 左键正常签到：截止时间前 present（绿）；右键请假：status=leave（橙）
//  - 补签请使用手动补签接口（POST /api/attendance/records，管理员/教师）
// ------------------------------------------------------------
router.post('/attendance/checkin', async (req, res, next) => {
  const { studentId, action, leaveReason, checkInMethod, columnIndex } = req.body;
  try {
    // 学生账号只读（与 batch-checkin / session-save 一致）：此前本接口缺这一道，
    // 学生只要知道 studentId 就能改签到 —— 前端隐藏控件不算权限边界，后端必须拦
    if (req.session.user.role === 'student') {
      return res.status(403).json({ error: '无权限：学生账号不可操作签到' });
    }
    if (!Number.isInteger(studentId)) {
      return res.status(400).json({ error: '缺少有效的 studentId' });
    }
    if (!['present', 'leave', 'cancel'].includes(action)) {
      return res.status(400).json({ error: 'action 必须是 present / leave / cancel' });
    }
    // 该学生必须在本账号的班级范围内（统一入口；管理员按 ?classId=/绑定班级收敛）
    const viewer = await viewerScope(req.session.user, req.body.classId);
    if (viewer.error) return res.status(viewer.status || 400).json({ error: viewer.error });
    const stuRow = await pool.query(
      "SELECT id, class_id FROM students WHERE id = $1 AND is_active = true AND status = '在读'",
      [studentId]
    );
    if (stuRow.rowCount === 0) return res.status(404).json({ error: '学生不存在' });
    const stuClassId = stuRow.rows[0].class_id || null;
    if (!viewer.schoolWideView && (!stuClassId || !viewer.classIds.includes(stuClassId))) {
      return res.status(403).json({ error: '无权限：该学生不属于你所带的班级' });
    }
    // 场次 = 该学生所在班级当前进行中的场次（优先本班专属，其次全校场次）
    //   v35（早/晚两场）：前端可显式传 sessionId 指定要登记的那一场（否则"最新一场"会让早自习登记到晚上去）
    let session = null;
    const wantSid = Number(req.body.sessionId);
    if (Number.isInteger(wantSid) && wantSid > 0) {
      const guardS = await assertSessionVisible(req.session.user, wantSid, { classId: req.body.classId });
      if (guardS.error) return res.status(guardS.status || 403).json({ error: guardS.error });
      session = (await pool.query(`SELECT ${SESSION_SELECT_COLS} FROM attendance_sessions WHERE id = $1`, [wantSid])).rows[0] || null;
      if (!session) return res.status(404).json({ error: '签到场次不存在' });
      if (session.status !== 'active') {
        return res.status(400).json({ error: '该场次已结束，不能登记（可在考勤分析中查看）' });
      }
      if (session.class_id !== null && stuClassId !== session.class_id) {
        return res.status(403).json({ error: '无权限：该学生不属于本场次对应的班级' });
      }
    } else {
      session = await activeSessionFor(stuClassId);
    }
    if (!session) {
      return res.status(400).json({ error: '当前没有进行中的签到，请先发起签到' });
    }
    // 签到窗口校验：present/leave 受窗口限制（截止后拒绝）；cancel 为纠错操作不受限
    // **每天自动签到（v35）例外**：auto 场次"不限时"（班长/班主任随时可录入）
    if (action !== 'cancel' && !session.auto_generated && new Date() > new Date(session.deadline)) {
      await finalizeAbsent(session.id);
      return res.status(400).json({ error: '签到窗口已关闭' });
    }
    const method = checkInMethod || 'manual';
    const colIdx = Number.isInteger(columnIndex) ? columnIndex : null;

    // 取消签到：删除本场次记录（恢复待签）
    if (action === 'cancel') {
      const r = await pool.query(
        'DELETE FROM attendance_records WHERE session_id = $1 AND student_id = $2',
        [session.id, studentId]
      );
      await logOperation(req, 'cancel_checkin', { studentId, sessionId: session.id });
      return res.json({ record: null, cancelled: r.rowCount > 0 });
    }

    // 校验学生存在
    const studentCheck = await pool.query(
      "SELECT id FROM students WHERE id = $1 AND is_active = true AND status = '在读'",
      [studentId]
    );
    if (studentCheck.rowCount === 0) {
      return res.status(404).json({ error: '学生不存在' });
    }

    // 同一场次下已存在记录的处理：
    //  - 自动标记的 absent 可被“迟到签到(present)”或“补请假(leave)”覆盖（第五步）
    //  - 其余状态（present/leave/late）拒绝重复操作
    const existing = await pool.query(
      `SELECT id, status, leave_reason, checkin_time
         FROM attendance_records
        WHERE session_id = $1 AND student_id = $2`,
      [session.id, studentId]
    );
    if (existing.rowCount > 0) {
      const rec = existing.rows[0];
      if (rec.status === 'absent') {
        // 缺勤覆盖：present → late（迟到，默认）；forcePresent=true（右键"修改为已签到"）→ 直接已签到（绿）
        //   每天自动签到（v35）没有时间概念（不限时）→ 一律记 present，不产生"迟到"
        if (action === 'present') {
          const target = (session.auto_generated === true || req.body.forcePresent === true || req.body.forcePresent === 'true') ? 'present' : 'late';
          const { rows } = await pool.query(
            `UPDATE attendance_records
                SET status = $2, leave_reason = NULL, checkin_time = now(),
                    check_in_method = $3, column_index = $4
              WHERE id = $1
             RETURNING id, status, leave_reason, checkin_time, check_in_method, column_index`,
            [rec.id, target, method, colIdx]
          );
          await logOperation(req, 'single_checkin', { studentId, sessionId: session.id, method, forced: target === 'present' });
          return res.status(200).json({ record: mapRecord(rows[0]), overridden: true });
        }
        // action === 'leave'：校验事由后覆盖为请假
        if (!leaveReason || !LEAVE_CODES.has(leaveReason)) {
          return res.status(400).json({
            error: '请假必须提供有效事由（sick=病假 / personal=事假 / official=公假）',
          });
        }
        const { rows } = await pool.query(
          `UPDATE attendance_records
              SET status = 'leave', leave_reason = $2, checkin_time = now(),
                  check_in_method = $3, column_index = $4
            WHERE id = $1
           RETURNING id, status, leave_reason, checkin_time, check_in_method, column_index`,
          [rec.id, leaveReason, method, colIdx]
        );
        await logOperation(req, 'leave_checkin', { studentId, sessionId: session.id, leaveReason });
        return res.status(200).json({ record: mapRecord(rows[0]), overridden: true });
      }
      return res.status(409).json({
        error: '该学生本场次已签到，不能重复操作',
        record: mapRecord(rec),
      });
    }

    let record;
    if (action === 'leave') {
      // 请假：必须提供有效事由
      if (!leaveReason || !LEAVE_CODES.has(leaveReason)) {
        return res.status(400).json({
          error: '请假必须提供有效事由（sick=病假 / personal=事假 / official=公假）',
        });
      }
      const { rows } = await pool.query(
        `INSERT INTO attendance_records (session_id, student_id, status, leave_reason, checkin_time, check_in_method, column_index)
         VALUES ($1, $2, 'leave', $3, now(), $4, $5)
         RETURNING id, status, leave_reason, checkin_time, check_in_method, column_index`,
        [session.id, studentId, leaveReason, method, colIdx]
      );
      record = rows[0];
      await logOperation(req, 'leave_checkin', { studentId, sessionId: session.id, leaveReason });
    } else {
      // 正常签到：由数据库时间统一判断迟到（截止时间之前=present，之后=late）
      //   每天自动签到（v35）：不限时 → 一律 present（$5=true 时跳过时间判断）
      const { rows } = await pool.query(
        `INSERT INTO attendance_records (session_id, student_id, status, leave_reason, checkin_time, check_in_method, column_index)
         SELECT $1, $2,
                CASE WHEN $5::boolean OR now() <= deadline THEN 'present' ELSE 'late' END,
                NULL, now(), $3, $4
           FROM attendance_sessions
          WHERE id = $1
         RETURNING id, status, leave_reason, checkin_time, check_in_method, column_index`,
        [session.id, studentId, method, colIdx, session.auto_generated === true]
      );
      record = rows[0];
      await logOperation(req, 'single_checkin', { studentId, sessionId: session.id, method });
    }

    res.status(201).json({ record: mapRecord(record) });
  } catch (err) {
    next(err);
  }
});


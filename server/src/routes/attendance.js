// ============================================================
// 签到「班级隔离」统一解析层（方案 A）
//   唯一真源 = attendance_sessions.class_id
//     · class_id IS NULL → 全校场次（历史"全部班级"计划 / 管理员发起）
//     · 非空          → 该班专属场次（"全部班级"计划触发时会**按班拆成多场**，每场一个班）
//   本节的函数是**所有读写场次接口的唯一入口**，不再从"计划 / 发起人 / 记录"推导归属
//   （那正是隔离问题反复出现的根因）。
// ============================================================

// 账号"所带班级"（班长=users.class_id；教师=users.class_id ∪ teacher_classes ∪ classes.head_teacher_id）
async function viewerClassIds(user) {
  if (!user || user.role === 'admin') return [];   // 管理员单独处理（见 viewerScope）
  const { rows } = await pool.query(
    `SELECT DISTINCT cid FROM (
        SELECT class_id AS cid FROM users WHERE id = $1 AND class_id IS NOT NULL
        UNION SELECT class_id FROM teacher_classes WHERE teacher_id = $1
        UNION SELECT id AS cid FROM classes WHERE head_teacher_id = $1
     ) t WHERE cid IS NOT NULL`,
    [user.id]
  );
  return rows.map((r) => r.cid);
}

// 当前账号在签到台关注的班级范围
//   · 班长/教师 → 自己（所带）的班级；displayClassId = 主班级（卡片/座位表按它显示）
//   · 管理员   → ?classId=<班级id> 指定该班；?classId=all / 0 / 不传 → 全校视角（不收敛）
//                （管理员保留"全校视角"是刻意设计：场次审计、补签、计划管理等管理页需要看全部；
//                  要只看某个班请在签到操作台用「查看班级」下拉，或显式传 ?classId=）
async function viewerScope(user, requestedClassId) {
  if (!user) return { classIds: [], displayClassId: null, isAdmin: false, schoolWideView: true };
  if (user.role === 'admin') {
    const raw = requestedClassId === undefined || requestedClassId === null ? '' : String(requestedClassId).trim();
    if (raw === '' || raw === 'all' || raw === '0') {
      return { classIds: [], displayClassId: null, isAdmin: true, schoolWideView: true };
    }
    const reqCid = Number(raw);
    if (Number.isInteger(reqCid) && reqCid > 0) {
      const c = await pool.query('SELECT id FROM classes WHERE id = $1', [reqCid]);
      if (c.rowCount === 0) return { error: '班级参数无效', status: 400 };
      return { classIds: [reqCid], displayClassId: reqCid, isAdmin: true, schoolWideView: false };
    }
    return { error: '班级参数无效', status: 400 };
  }
  const ids = await viewerClassIds(user);
  return { classIds: ids, displayClassId: ids[0] || null, isAdmin: false, schoolWideView: ids.length === 0 };
}

// 场次归属（唯一真源）
async function sessionScopeOf(sessionId) {
  const { rows } = await pool.query(
    `SELECT id, class_id, status, auto_generated, slot, session_date FROM attendance_sessions WHERE id = $1`,
    [sessionId]
  );
  const row = rows[0];
  if (!row) return null;
  return {
    sessionId: row.id, classId: row.class_id || null, schoolWide: row.class_id === null,
    status: row.status, autoGenerated: row.auto_generated === true, slot: row.slot || null,
    sessionDate: row.session_date || null,
  };
}

// 读/写场次的统一鉴权入口：别的班（且非全校）的场次一律 403
async function assertSessionVisible(user, sessionId, opts = {}) {
  const viewer = await viewerScope(user, opts.classId);
  if (viewer.error) return { error: viewer.error, status: viewer.status };
  const s = await sessionScopeOf(sessionId);
  if (!s) return { error: '签到场次不存在', status: 404 };
  const visible = viewer.schoolWideView || s.schoolWide ||
    (s.classId !== null && viewer.classIds.includes(s.classId));
  if (!visible) return { error: '无权限：该场次不属于你所带的班级', status: 403, session: s };
  return { ok: true, session: s, viewer };
}

// 某班当前进行中的场次：优先"本班专属"，其次"全校场次"(class_id IS NULL)
//   classId 为空 → 全局最新进行中场次（管理员全校视角 / 内部调用）
// 场次查询统一列（v35 起含 auto_generated / slot / session_date：前端要据此显示「早自习/晚自修」，
// 并区分"系统自动生成、不限时"的场次与老的手动/计划场次）
const SESSION_SELECT_COLS = `id, start_time, deadline, status, created_by, created_by_name, created_by_role,
        start_source, deadline_minutes, class_id, auto_generated, slot, session_date`;

// /attendance/status 里"顺手推进计划"的节流时间戳（模块级：见该路由有进行中场次时的 else 分支）
let lastPlanLazyTriggerAt = 0;

// 当前进行中的场次（不带 slot 的调用方用：老接口/缓存页面/批量操作）
//   排序优先级（v35 修正）：
//     ① 本班专属优先（老规则）
//     ② 老场次（手动发起/计划触发）优先 —— 它是"老师现在正在做的那一场"，老行为完全不变
//     ③ 都是自动场次时，**按当前时间段**选：中午前=早自习、中午后=晚自修
//        （此前一律 `id DESC` → 一天两场时永远取到晚自修，导致"看着早自习却写进晚自修"，
//          2026-09-30 真实反馈的 BUG 就是这个根因）
//     ④ 最后 id DESC 兜底
function preferredAutoSlot(now = new Date()) { return now.getHours() < 12 ? 'morning' : 'evening'; }

async function activeSessionFor(classId, client = pool) {
  const sel = `SELECT ${SESSION_SELECT_COLS}
                 FROM attendance_sessions WHERE status = 'active'`;
  const wantSlot = preferredAutoSlot();
  const cid = Number(classId);
  if (Number.isInteger(cid) && cid > 0) {
    const { rows } = await client.query(
      `${sel} AND (class_id = $1 OR class_id IS NULL)
       ORDER BY CASE WHEN class_id = $1 THEN 0 ELSE 1 END,
                (auto_generated = true) ASC,
                CASE WHEN auto_generated = true AND slot = $2 THEN 0 ELSE 1 END,
                id DESC LIMIT 1`,
      [cid, wantSlot]
    );
    return rows[0] || null;
  }
  // 全局（管理员全校视角）：占位符必须与参数个数一致（曾因用 $2 却只传 1 个参数 → 500）
  const { rows } = await client.query(
    `${sel}
     ORDER BY (auto_generated = true) ASC,
              CASE WHEN auto_generated = true AND slot = $1 THEN 0 ELSE 1 END,
              id DESC LIMIT 1`,
    [wantSlot]
  );
  return rows[0] || null;
}

// ------------------------------------------------------------
// 每天自动生成的「早/晚」场次解析（v35 · 阶段 2）
//   为什么需要：以前"当前场次" = 最新的 active 场次（id DESC）—— 一旦一天两场都是 active，
//   早自习就会被晚自修顶掉（班长早上打开看到的是晚自修）。带 slot 的读取必须**按 (班级+日期+时段) 直查**。
//   · slot 给定 → 精确取该时段（不限 status：已收口 closed 的也要能回看）
//   · 只给 date 不给 slot → 取当天**最早**一场（morning 优先），行为确定
//   · 都不给 → null（走原有 active / 结束回看逻辑，老行为完全不变）
// ------------------------------------------------------------
async function autoSessionFor(classId, dateStr, slot, client = pool) {
  const cid = Number(classId);
  if (!Number.isInteger(cid) || cid <= 0) return null;
  const date = isValidDateStr(dateStr) ? dateStr : todayStr();
  const wantSlot = (slot === 'morning' || slot === 'evening') ? slot : null;
  const params = [cid, date];
  let slotCond = '';
  if (wantSlot) { params.push(wantSlot); slotCond = ` AND slot = $${params.length}`; }
  const { rows } = await client.query(
    `SELECT ${SESSION_SELECT_COLS}
       FROM attendance_sessions
      WHERE auto_generated = true AND class_id = $1 AND session_date = $2::date${slotCond}
      ORDER BY CASE slot WHEN 'morning' THEN 0 ELSE 1 END, id
      LIMIT 1`,
    params
  );
  return rows[0] || null;
}

// 场次时段中文（早自习/晚自修）；老场次返回 null
function slotLabelOf(session) {
  if (!session || !session.slot) return null;
  if (session.slot === 'morning') return '早自习';
  if (session.slot === 'evening') return '晚自修';
  return null;
}

// 今天最近一场【对本账号可见】的已结束场次（结束回看 / 导出共用）
async function lastVisibleClosedSessionToday(viewer) {
  const today = new Date();
  today.setHours(0, 0, 0, 0);
  const params = [today];
  let where = `s.status = 'closed' AND s.start_time >= $1`;
  if (!viewer.schoolWideView) {
    params.push(viewer.classIds);
    where += ` AND (s.class_id IS NULL OR s.class_id = ANY($2::int[]))`;
  }
  const { rows } = await pool.query(
    `SELECT ${SESSION_SELECT_COLS.split(',').map((c) => 's.' + c.trim()).join(', ')}
       FROM attendance_sessions s WHERE ${where} ORDER BY s.id DESC LIMIT 1`,
    params
  );
  return rows[0] || null;
}

// ------------------------------------------------------------
// GET /api/attendance/status —— 获取当前签到状态
// 返回：进行中的场次、各学生签到记录、实时统计
// 惰性触发：无进行中场次时，若存在已到点的 pending 计划则立即触发
// （不必等 60 秒调度周期，保证"计划签到中"时签到页立即可用）
// ------------------------------------------------------------
router.get('/attendance/status', async (req, res, next) => {
  try {
    let session = null;
    let isEndedView = false; // 展示最近已结束场次的最终结果
    let pinned = false;      // 前端指定的场次（钉住自己正在登记的那一场）
    let hiddenSession = null; // 被"班级隔离"挡掉的场次（本班未涉及）→ 仅用于给页面提示
    // 班级范围（唯一入口）：班长/教师 = 自己的班；管理员 = ?classId= 指定 > 绑定班级 > 全校视角
    const viewer = await viewerScope(req.session.user, req.query.classId);
    if (viewer.error) return res.status(viewer.status || 400).json({ error: viewer.error });
    const myClassIds = viewer.classIds;
    const displayClassId = viewer.displayClassId;   // 卡片/座位表按它显示（一个班）
    // ---- 每天自动签到（v35 · 阶段 2）：?date=YYYY-MM-DD&slot=morning|evening ----
    //   两场并存时必须按时段直查（否则 activeSessionFor 的"最新一场"会让早自习被晚自修顶掉）。
    //   未传 slot 时取当天最早一场（morning 优先）；未传 date 则默认今天。
    const reqSlot = String(req.query.slot || '').trim();
    const reqDate = String(req.query.date || '').trim();
    let autoRequested = false;
    if (reqSlot === 'morning' || reqSlot === 'evening' || (isValidDateStr(reqDate) && req.query.auto === '1')) {
      autoRequested = true;
    }
    // 指定场次：前端把"本页正在登记"的场次 id 带上来，避免被其它场次（计划自动触发等）
    // 顶掉后已签到记录看起来"全部消失/变成缺勤"。仅允许近两天内的场次，防止任意探测历史。
    // 同时做班级可见性校验：钉住的场次若不属于本班（且非全校场次）→ 不采用该钉住。
    const pinnedId = Number(req.query.sessionId);
    if (Number.isInteger(pinnedId) && pinnedId > 0) {
      const pin = await pool.query(
        `SELECT ${SESSION_SELECT_COLS}
           FROM attendance_sessions
          WHERE id = $1 AND start_time >= (CURRENT_DATE - 1)`,
        [pinnedId]
      );
      if (pin.rowCount > 0) {
        const row = pin.rows[0];
        const ok = viewer.schoolWideView || row.class_id === null ||
          myClassIds.includes(row.class_id);
        if (ok) {
          session = row;
          isEndedView = session.status !== 'active';
          pinned = true;
        } else {
          hiddenSession = {
            id: row.id, startTime: row.start_time, startSource: row.start_source || 'manual',
            createdByName: row.created_by_name || null, classId: row.class_id || null, reason: 'other-class',
          };
        }
      }
    }
    // 自动场次（带 slot / auto=1 的读取）：精确按 (班级, 日期, 时段) 取；取不到则回落到老逻辑
    if (!session && autoRequested) {
      const auto = await autoSessionFor(displayClassId, isValidDateStr(reqDate) ? reqDate : todayStr(), reqSlot);
      if (auto) {
        session = auto;
        isEndedView = auto.status !== 'active';
      }
    }
    // 当前进行中的场次：本班专属优先，其次全校场次（按 class_id 直查，不再推导）
    if (!session) session = await activeSessionFor(displayClassId);
    if (session) {
      const visible = viewer.schoolWideView || session.class_id === null || myClassIds.includes(session.class_id);
      if (!visible) {
        hiddenSession = {
          id: session.id,
          startTime: session.start_time,
          startSource: session.start_source || 'manual',
          createdByName: session.created_by_name || null,
          classId: session.class_id || null,
          reason: 'other-class',
        };
        console.log(`[班级隔离] 场次#${session.id}（归属班级 ${session.class_id}）与账号 ${req.session.user.id} 的班级无关 → 不显示`);
        session = null;
      }
    }
    if (!session) {
      try {
        await triggerDuePlans(); // 幂等
        const triggered = await activeSessionFor(displayClassId);
        if (triggered) {
          const ok = viewer.schoolWideView || triggered.class_id === null || myClassIds.includes(triggered.class_id);
          if (ok) session = triggered;
          else hiddenSession = hiddenSession || {
            id: triggered.id, startTime: triggered.start_time, startSource: triggered.start_source || 'manual',
            createdByName: triggered.created_by_name || null, classId: triggered.class_id || null, reason: 'other-class',
          };
        }
      } catch (_) { /* 触发失败不影响状态返回 */ }
    } else {
      // 有进行中的场次时也要"顺手"推进计划状态（标记过期计划为 ended 等）——
      //   v35 起每天自动签到会让班级整天都有进行中的场次，原来"没场次才触发"的懒执行就再也不跑了，
      //   计划管理里会积压"待签到"僵尸计划。
      //   节流策略：**只要还有 pending 计划就立刻触发**（计划是少量、临时的），
      //             没有 pending 计划时最多每 30 秒触发一次（避免每次 3 秒轮询都全量检查）。
      const nowMs = Date.now();
      let hasPending = false;
      try {
        hasPending = (await pool.query("SELECT count(*)::int AS n FROM attendance_plans WHERE status = 'pending'")).rows[0].n > 0;
      } catch (_) { /* 查询失败按"无 pending"处理 */ }
      if (hasPending || nowMs - lastPlanLazyTriggerAt > 30000) {
        lastPlanLazyTriggerAt = nowMs;
        try { await triggerDuePlans(); } catch (_) { /* 同上，失败不影响状态返回 */ }
      }
    }
    if (!session) {
      // 回退：当天最近一场【对本账号可见】的已结束场次（结束回看）
      const last = await lastVisibleClosedSessionToday(viewer);
      if (last) {
        session = last;
        isEndedView = true;
      }
    }

    // 学生列表范围：
    //   · 账号绑定了班级（users.class_id）→ 只显示该班（座位表/卡片就是这一个班）
    //   · 未绑定但有所带班级（教师带班关系）→ 显示所带班级（避免"没绑班就看到全校学生"）
    //   · 管理员/无任何班级 → 全部在读学生（保持原行为）
    const displayClassIds = displayClassId ? [displayClassId] : myClassIds;
    const studentsRes = await pool.query(
      "SELECT id FROM students WHERE is_active = true AND status = '在读'" +
        ((displayClassIds && displayClassIds.length) ? ' AND class_id = ANY($1::int[])' : '') +
        ' ORDER BY student_no',
      (displayClassIds && displayClassIds.length) ? [displayClassIds] : []
    );

    const records = {};
    const stats = {
      total: studentsRes.rowCount,
      present: 0,
      leave: 0,
      late: 0,
      absent: 0,
    };
    const displayIds = new Set(studentsRes.rows.map((x) => x.id));

    if (session) {
      // 截止时间已到 → 懒执行补缺勤 + 标记场次已结束（closed）
      // （手动发起的场次也由此自动结束，进入考勤分析统计）
      // **每天自动签到（v35）例外**：auto 场次"不限时"，且"没有记录"= 老师还没登记（不是学生缺勤），
      //   所以既不补缺勤也不自动收口 —— 收口只由次日 0 点的 closeStaleAutoSessions() 统一完成。
      //   若不豁免，晚自修场次一过 23:59 就会把整班刷成缺勤（这正是新模型要避免的）。
      if (!session.auto_generated && new Date() > new Date(session.deadline)) {
        await finalizeAbsent(session.id);
        await pool.query(
          `UPDATE attendance_sessions SET status = 'closed' WHERE id = $1 AND status = 'active'`,
          [session.id]
        );
        session.status = 'closed';
      }

      const { rows } = await pool.query(
        `SELECT student_id, status, leave_reason, checkin_time, check_in_method, column_index
           FROM attendance_records
          WHERE session_id = $1`,
        [session.id]
      );
      for (const r of rows) {
        if (!displayIds.has(r.student_id)) continue; // 跳过已删除/非本班学生的历史记录
        records[r.student_id] = mapRecord(r);
        if (r.status in stats) stats[r.status] += 1;
      }
    }

    // ---- 当天「全天请假」登记直接反映到卡片与统计 ----
    //   为什么：全天请假是"按天"的事实。若当前没有进行中的场次（或该场次不含本班 —— 班级隔离后很常见），
    //   班长的签到操作台仍应看到这些学生**橙色请假**，否则会出现"教师已登记请假、班长端请假 0 / 未签到"
    //   （用户反馈的同步问题）。真实签到（present/late）优先，不被覆盖。
    const dlRes = await pool.query(
      `SELECT dl.student_id, dl.reason
         FROM student_day_leaves dl
         JOIN students s ON s.id = dl.student_id AND s.is_active = true AND s.status = '在读'
        WHERE dl.leave_date = CURRENT_DATE
          AND ($1::int[] IS NULL OR s.class_id = ANY($1::int[]))`,
      [(displayClassIds && displayClassIds.length) ? displayClassIds : null]
    );
    const dayLeaveIds = [];
    for (const row of dlRes.rows) {
      if (!displayIds.has(row.student_id)) continue;
      const cur = records[row.student_id];
      // 已签到/迟到：真实记录优先（**每天自动签到除外**：它的 present 是"默认全员已签"/整场保存，
      //   不是学生签名 → 全天请假要覆盖显示，否则老师登记了病假却看到"已签到"）
      const isAutoSession = !!(session && session.auto_generated);
      if (cur && (cur.status === 'present' || cur.status === 'late') && !(isAutoSession && cur.status === 'present')) continue;
      if (cur && cur.status === 'leave' && cur.leaveReason === row.reason) {
        cur.dayLeave = true;                                                     // 场次里已是同一条请假
        dayLeaveIds.push(row.student_id);
        continue;
      }
      records[row.student_id] = {
        status: 'leave',
        leaveReason: row.reason,
        checkinTime: (cur && cur.checkinTime) || null,
        checkInMethod: DAY_LEAVE_METHOD,
        columnIndex: (cur && cur.columnIndex) || null,
        dayLeave: true,                                                          // 来自「当天全天请假」登记
      };
      dayLeaveIds.push(row.student_id);
    }
    // 叠加后重算统计，保证 stats 与最终 records 完全一致
    stats.present = 0; stats.leave = 0; stats.late = 0; stats.absent = 0;
    for (const id of Object.keys(records)) {
      const st = records[id].status;
      if (Object.prototype.hasOwnProperty.call(stats, st)) stats[st] += 1;
    }

    res.json({
      session: session
        ? {
            id: session.id,
            startTime: session.start_time,
            deadline: session.deadline,
            status: session.status,
            ended: isEndedView,
            // 发起人追溯：手动发起（manual）记录操作者；计划触发（plan）记录计划创建人；历史数据为 null
            createdBy: session.created_by || null,
            createdByName: session.created_by_name || null,
            createdByRole: session.created_by_role || null,
            startSource: session.start_source || 'manual',
            deadlineMinutes: session.deadline_minutes || null,
            // 场次归属班级（NULL = 全校场次）：前端据此做二次校验
            classId: session.class_id || null,
            // ---- 每天自动签到（v35）：系统生成 / 时段 / 归属日期 ----
            //   前端据此：显示「早自习/晚自修」、不显示倒计时与截止时间、提示"不限时"
            autoGenerated: session.auto_generated === true,
            slot: session.slot || null,
            slotLabel: slotLabelOf(session),
            sessionDate: session.session_date ? fmtDate(session.session_date) : null,
          }
        : null,
      pinned,
      records,
      stats,
      // 当天自动签到场次概览（早/晚各一场 + 各自进度），供页面做"早自习/晚自修"两块切换
      autoSessions: await (async () => {
        if (!displayClassId) return [];
        const date = isValidDateStr(reqDate) ? reqDate : todayStr();
        const rows = (await pool.query(
          `SELECT s.id, s.slot, s.status, s.session_date,
                  (SELECT count(*) FROM attendance_records r WHERE r.session_id = s.id) AS marked,
                  (SELECT count(*) FROM attendance_records r WHERE r.session_id = s.id AND r.status = 'present') AS present,
                  (SELECT count(*) FROM attendance_records r WHERE r.session_id = s.id AND r.status = 'absent') AS absent,
                  (SELECT count(*) FROM attendance_records r WHERE r.session_id = s.id AND r.status = 'leave') AS leave
             FROM attendance_sessions s
            WHERE s.auto_generated = true AND s.class_id = $1 AND s.session_date = $2::date
            ORDER BY CASE s.slot WHEN 'morning' THEN 0 ELSE 1 END, s.id`, [displayClassId, date]
        )).rows;
        return rows.map((r) => ({
          id: r.id, slot: r.slot, label: slotLabelOf(r), status: r.status, sessionDate: fmtDate(r.session_date),
          marked: Number(r.marked), present: Number(r.present), absent: Number(r.absent), leave: Number(r.leave),
        }));
      })(),
      // 当天「全天请假」摘要（前端/用例据此核对同步情况）
      dayLeaves: { count: dayLeaveIds.length, studentIds: dayLeaveIds },
      // 班级隔离信息（供页面提示/排查）：本账号关注的班级、被挡掉的"别的班场次"
      scope: {
        role: req.session.user.role,
        classIds: myClassIds,               // 空数组 = 不收敛（管理员未指定班级且未绑定）
        displayClassIds: displayClassIds || [],
        schoolWideView: viewer.schoolWideView,
      },
      hiddenSession,                   // 非 null 时：当前有进行中的场次，但与本班无关 → 不显示
    });
  } catch (err) {
    next(err);
  }
});

// ------------------------------------------------------------
// POST /api/students/import —— 批量导入学生名单
// body: { students: [{ studentNo, name, className? }, ...] }
//  - className 为班级名（可选），按 classes.class_name 精确匹配
//  - 学号冲突自动跳过（不覆盖已有名单），班级不存在的学生计入 classNotFound
// ------------------------------------------------------------
router.post('/students/import', async (req, res, next) => {
  try {
    const list = req.body && req.body.students;
    if (!Array.isArray(list) || list.length === 0) {
      return res.status(400).json({ error: '缺少学生数据' });
    }
    if (list.length > 5000) {
      return res.status(400).json({ error: '单次导入不能超过 5000 人' });
    }

    const valid = [];
    const seen = new Set();
    let invalidCount = 0;
    for (const item of list) {
      const studentNo = String(item.studentNo ?? '').trim();
      const name = String(item.name ?? '').trim();
      const className = String(item.className ?? '').trim();
      if (!studentNo || !name) { invalidCount += 1; continue; }
      if (seen.has(studentNo)) continue; // 同一批内去重
      seen.add(studentNo);
      // 透传扩展档案字段（学生信息扩展）
      const profile = {};
      for (const [key] of STUDENT_PROFILE_COLS) {
        if (item[key] !== undefined && item[key] !== null) {
          profile[key] = String(item[key]).trim();
        }
      }
      valid.push({ studentNo, name, className, profile });
    }
    if (valid.length === 0) {
      return res.status(400).json({ error: '没有有效的学生数据（需要学号+姓名）' });
    }

    // 收集本批出现的班级名，批量查询 class_id
    const classNames = [...new Set(valid.map((s) => s.className).filter(Boolean))];
    const classMap = {};
    if (classNames.length > 0) {
      const { rows } = await pool.query(
        'SELECT id, class_name FROM classes WHERE class_name = ANY($1)',
        [classNames]
      );
      for (const r of rows) classMap[r.class_name] = r.id;
    }

    // 拆分：班级存在可插入 / 班级不存在
    const toInsert = [];
    let classNotFound = 0;
    for (const s of valid) {
      if (s.className) {
        const cid = classMap[s.className];
        if (!cid) { classNotFound += 1; continue; }
        toInsert.push({ studentNo: s.studentNo, name: s.name, classId: cid, profile: s.profile });
      } else {
        toInsert.push({ studentNo: s.studentNo, name: s.name, classId: null, profile: s.profile });
      }
    }

    let inserted = 0;
    let reactivated = 0;
    for (const s of toInsert) {
      // 学号冲突时同步姓名/班级并重新启用（名单同步，可恢复已删除学生）
      // xmax=0 表示新插入，否则为冲突更新（含恢复已删除学生）
      const r = await pool.query(
        `INSERT INTO students (student_no, name, class_id) VALUES ($1, $2, $3)
         ON CONFLICT (student_no) DO UPDATE
            SET name = EXCLUDED.name,
                class_id = EXCLUDED.class_id,
                is_active = true,
                status = '在读',
                deleted_at = NULL
         RETURNING (xmax = 0) AS is_insert, id`,
        [s.studentNo, s.name, s.classId]
      );
      // 写入扩展档案字段
      await applyStudentProfile(r.rows[0].id, s.profile);
      if (r.rows[0].is_insert) inserted += 1;
      else reactivated += 1;
    }

    res.status(201).json({
      inserted,
      reactivated,
      skipped: valid.length - inserted - reactivated - classNotFound,
      classNotFound,
      invalid: invalidCount,
      total: valid.length,
    });
  } catch (err) {
    next(err);
  }
});


router.get('/attendance/daily-sessions/config', async (req, res, next) => {
  try {
    if (!req.session.user) return res.status(401).json({ error: '未登录' });
    const enabled = await dailySessionsEnabled();
    const rows = (await pool.query(
      `SELECT s.id, s.class_id, c.class_name, s.slot, s.session_date, s.status, s.start_time, s.deadline,
              (SELECT count(*) FROM attendance_records r WHERE r.session_id = s.id) AS record_count
         FROM attendance_sessions s LEFT JOIN classes c ON c.id = s.class_id
        WHERE s.auto_generated = true AND s.session_date = CURRENT_DATE
        ORDER BY s.class_id, CASE s.slot WHEN 'morning' THEN 0 ELSE 1 END`
    )).rows;
    res.json({
      enabled,
      settingKey: DAILY_SESSIONS_ENABLED_KEY,
      slots: DAILY_SESSION_SLOTS.map((s) => ({ ...s, deadlineText: DAILY_SESSION_DEADLINE })),
      note: '不限时：auto 场次不做签到窗口校验；进页面默认全员已签，点「保存」才整场落库',
      todaySessions: rows.map((r) => ({
        id: r.id, classId: r.class_id, className: r.class_name, slot: r.slot,
        sessionDate: fmtDate(r.session_date), status: r.status,
        startTime: r.start_time, deadline: r.deadline, recordCount: Number(r.record_count),
      })),
    });
  } catch (err) { next(err); }
});

router.put('/attendance/daily-sessions/config', async (req, res, next) => {
  try {
    const me = req.session.user;
    if (!me) return res.status(401).json({ error: '未登录' });
    if (me.role !== 'admin') return res.status(403).json({ error: '仅管理员可修改每日签到设置' });
    const raw = req.body ? req.body.enabled : undefined;
    if (raw === undefined) return res.status(400).json({ error: '缺少 enabled' });
    const value = (raw === true || raw === 1 || raw === '1' || raw === 'true' || raw === 'on') ? '1' : '0';
    await pool.query(
      `INSERT INTO system_settings (key, value, updated_at) VALUES ($1, $2, now())
       ON CONFLICT (key) DO UPDATE SET value = EXCLUDED.value, updated_at = now()`,
      [DAILY_SESSIONS_ENABLED_KEY, value]
    );
    // 打开时立即生成当天场次（幂等）→ 管理员可当场核对
    let created = null;
    if (value === '1') {
      const closed = await closeStaleAutoSessions(todayStr());
      const r = await generateDailySessionsForAllClasses(todayStr());
      created = { ...r, closed };
      await pool.query(
        `INSERT INTO operation_logs (user_id, user_name, role, action, detail)
         VALUES ($1, $2, 'admin', 'daily_sessions_toggle', $3)`,
        [me.id, me.real_name || me.display_name || me.username,
          JSON.stringify({ enabled: value, classes: r.classes, created: r.created, closed, createdByClass: r.createdByClass })]
      ).catch(() => {});
    } else {
      await pool.query(
        `INSERT INTO operation_logs (user_id, user_name, role, action, detail)
         VALUES ($1, $2, 'admin', 'daily_sessions_toggle', $3)`,
        [me.id, me.real_name || me.display_name || me.username, JSON.stringify({ enabled: value })]
      ).catch(() => {});
    }
    res.json({ enabled: value === '1', created });
  } catch (err) { next(err); }
});


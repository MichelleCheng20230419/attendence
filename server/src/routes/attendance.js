// GET /api/plans —— 计划列表（可按状态筛选）
// 参数：status?
//   ''            全部
//   'open'        签到中 + 待签到（计划管理页默认筛选，不显示已结束）
//   'pending' / 'active' / 'ended'  单个状态
//   'pending,active'                多状态（逗号分隔，兼容写法）
// 排序：签到中在最前 → 待签到按日期/时间升序 → 已结束按日期/时间倒序（最近的在前面）
// 教师：只显示本班计划（class_id = 自己班级 或 NULL 全校）
router.get('/plans', async (req, res, next) => {
  try {
    const statusRaw = String(req.query.status || '').trim();
    const VALID = ['pending', 'active', 'ended'];
    const p = [];
    let where = '';
    let statuses = [];
    if (statusRaw === 'open') {
      statuses = ['pending', 'active'];
    } else if (statusRaw) {
      statuses = statusRaw.split(',').map((s) => s.trim()).filter((s) => VALID.includes(s));
    }
    if (statuses.length === 1) {
      where = 'WHERE p.status = $1';
      p.push(statuses[0]);
    } else if (statuses.length > 1) {
      where = 'WHERE p.status = ANY($1::varchar[])';
      p.push(statuses);
    }
    // 教师：只可见本班 + 全校计划
    if (req.session.user.role === 'teacher') {
      const me = await pool.query('SELECT class_id FROM users WHERE id = $1', [req.session.user.id]);
      const myClassId = (me.rows[0] && me.rows[0].class_id) || 0;
      const cond = `(p.class_id = $${p.length + 1} OR p.class_id IS NULL)`;
      if (where) where += ' AND ' + cond;
      else where = 'WHERE ' + cond;
      p.push(myClassId);
    }
    const { rows } = await pool.query(
      `SELECT p.id, p.plan_date, p.start_time, p.duration_minutes, p.status, p.session_id, p.class_id,
              c.class_name AS class_name,
              s.deadline, s.start_time AS session_start
         FROM attendance_plans p
         LEFT JOIN classes c ON c.id = p.class_id
         LEFT JOIN attendance_sessions s ON s.id = p.session_id
         ${where}
        ORDER BY CASE p.status WHEN 'active' THEN 0 WHEN 'pending' THEN 1 ELSE 2 END,
                 CASE WHEN p.status = 'ended' THEN p.plan_date END DESC NULLS LAST,
                 CASE WHEN p.status <> 'ended' THEN p.plan_date END ASC NULLS LAST,
                 CASE WHEN p.status = 'ended' THEN p.start_time END DESC NULLS LAST,
                 p.start_time ASC`,
      p
    );
    res.json({
      plans: rows.map((r) => ({
        id: r.id,
        planDate: fmtPlanDate(r.plan_date),
        startTime: String(r.start_time).slice(0, 5),
        durationMinutes: r.duration_minutes,
        status: r.status,
        sessionId: r.session_id,
        classId: r.class_id,
        className: r.class_name || null,
        sessionStart: r.session_start ? r.session_start.toISOString() : null,
        sessionDeadline: r.deadline ? r.deadline.toISOString() : null,
      })),
    });
  } catch (err) {
    next(err);
  }
});


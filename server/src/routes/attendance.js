// 每天自动生成「早/晚 2 次签到」场次（v35 · 路线 B）
//   参照「每日作业」的模式：系统 0 点生成 + 幂等 + 启动补发 + 次日收口。
//   规则（与老师确认的口径）：
//     · 每个"有在读学生"的班级每天 2 场：morning=早自习 / evening=晚自修
//     · **不限时**：auto 场次不做任何签到窗口校验（阶段 2 落地），deadline 仅填当天 23:59 供兼容/展示
//     · **默认全签**：进页面默认"全员已签到"，只点掉没来的人；点「保存」把整场写库
//       （路线 B：不预建记录行，保存时才写显式 present/absent/leave —— 缺勤仍是真实数据，统计口径不变）
//     · **次日收口**：生成新一天时把昨天及更早仍未结束的 auto 场次置 closed，
//       且**不调用 finalizeAbsent()**（新模型里"没有记录"= 还没登记，不等于"学生缺勤"）
//     · 受 system_settings.daily_sessions_enabled 控制（默认关闭）：迁移/生成器可先上线不生效，
//       等前端与统计口径改造完成后再打开（灰度试点友好）
// ============================================================
const DAILY_SESSIONS_ENABLED_KEY = 'daily_sessions_enabled';
const DAILY_SESSION_SLOTS = [
  { slot: 'morning', label: '早自习' },
  { slot: 'evening', label: '晚自修' },
];
const DAILY_SESSION_DEADLINE = '23:59';   // 仅用于兼容 deadline NOT NULL；auto 场次不受其限制

// 今天（本地时区）YYYY-MM-DD —— 复用文件已有的 fmtDate()（支持 Date/字符串，见「工具函数」段）
function todayStr() { return fmtDate(new Date()); }

// 每天自动签到是否启用（system_settings.daily_sessions_enabled='1'）
async function dailySessionsEnabled() {
  try {
    const r = await pool.query('SELECT value FROM system_settings WHERE key = $1', [DAILY_SESSIONS_ENABLED_KEY]);
    const v = String((r.rows[0] && r.rows[0].value) || '').trim().toLowerCase();
    return v === '1' || v === 'true' || v === 'on';
  } catch (_) {
    return false;
  }
}

// 为单个班生成当天的早/晚 2 场（幂等：靠部分唯一索引 uniq_session_auto_slot）
//   start_time = 生成时刻（不用 07:30/19:00：考勤分析只统计 start_time <= now() 的场次，
//   用未来时刻会让当天早晨的分析看不到该场次；"早/晚"由 slot 表达）
async function ensureDailySessionsForClass(classId, dateStr) {
  const created = [];
  for (const { slot } of DAILY_SESSION_SLOTS) {
    const r = await pool.query(
      `INSERT INTO attendance_sessions
         (start_time, deadline, status, created_by, created_by_name, created_by_role,
          start_source, deadline_minutes, class_id, auto_generated, slot, session_date)
       VALUES (now(), ($1::date + $2::time), 'active', NULL, '系统', 'system',
               'auto', NULL, $3, true, $4, $1::date)
       ON CONFLICT (class_id, session_date, slot) WHERE auto_generated DO NOTHING
       RETURNING id`,
      [dateStr, DAILY_SESSION_DEADLINE, classId, slot]
    );
    if (r.rowCount > 0) created.push({ slot, id: r.rows[0].id });
  }
  return created;
}

// 为所有"有在读学生"的班级生成当天场次（归档班级、空班级不生成）
//   返回明细便于日志/测试断言；不抛错（单个班失败不影响其它班）
async function generateDailySessionsForAllClasses(dateStr) {
  const date = isValidDateStr(dateStr) ? dateStr : todayStr();
  const classes = (await pool.query(
    `SELECT c.id, c.class_name FROM classes c
      WHERE c.status IS DISTINCT FROM 'archived'
        AND EXISTS (SELECT 1 FROM students s
                     WHERE s.class_id = c.id AND s.is_active = true AND s.status = '在读')
      ORDER BY c.id`
  )).rows;
  const out = { date, classes: classes.length, created: 0, skipped: 0, createdByClass: [], slotCounts: { morning: 0, evening: 0 } };
  for (const c of classes) {
    try {
      const created = await ensureDailySessionsForClass(c.id, date);
      if (created.length) {
        out.created += created.length;
        for (const x of created) out.slotCounts[x.slot] += 1;
        out.createdByClass.push({ classId: c.id, className: c.class_name, created: created.map((x) => x.slot), sessions: created.map((x) => x.id) });
      } else {
        out.skipped += 1;
      }
    } catch (e) {
      console.error(`[每日签到自动生成] 班级#${c.id}（${c.class_name}）失败：`, e.message);
    }
  }
  return out;
}

// 次日收口：把"今天之前"仍未结束的自动场次置 closed
//   **刻意不调用 finalizeAbsent()** —— 新模型下没有记录 = 老师尚未登记，不能当成学生缺勤；
//   若在此补缺勤，会把"还没录"整班刷成缺勤（这正是本模型要避免的）
async function closeStaleAutoSessions(todayDateStr) {
  const date = isValidDateStr(todayDateStr) ? todayDateStr : todayStr();
  const r = await pool.query(
    `UPDATE attendance_sessions
        SET status = 'closed'
      WHERE auto_generated = true AND status = 'active' AND session_date < $1::date
      RETURNING id`,
    [date]
  );
  return r.rowCount;
}

let dailySessionTimer = null;
async function runDailySessionsAuto(tag) {
  try {
    if (!(await dailySessionsEnabled())) {
      console.log(`[每日签到自动生成${tag ? '·' + tag : ''}] 未启用（system_settings.${DAILY_SESSIONS_ENABLED_KEY} != 1）→ 跳过`);
      return { skipped: true, reason: 'disabled' };
    }
    const date = todayStr();
    const closed = await closeStaleAutoSessions(date);
    const r = await generateDailySessionsForAllClasses(date);
    console.log(`[每日签到自动生成${tag ? '·' + tag : ''}] ${r.date}：${r.classes} 个班，新建 ${r.created} 场（早 ${r.slotCounts.morning} / 晚 ${r.slotCounts.evening}），已存在跳过 ${r.skipped} 个班；收口往日 ${closed} 场`);
    if (r.created > 0 || closed > 0) {
      await pool.query(
        `INSERT INTO operation_logs (user_id, user_name, role, action, detail)
         VALUES (NULL, '系统', 'system', 'daily_sessions_auto', $1)`,
        [JSON.stringify({ date: r.date, classes: r.classes, created: r.created, closed, createdByClass: r.createdByClass })]
      ).catch(() => {});
    }
    return { ...r, closed };
  } catch (e) {
    console.error('[每日签到自动生成失败]', e.message);
    return null;
  }
}

function msUntilNextMidnight2(now = new Date(), offsetMs = 8000) {
  const next = new Date(now.getFullYear(), now.getMonth(), now.getDate() + 1, 0, 0, 0, 0);
  return Math.max(1000, next.getTime() - now.getTime() + offsetMs);
}

function scheduleNextDailySessionRun() {
  const wait = msUntilNextMidnight2();
  dailySessionTimer = setTimeout(async () => {
    await runDailySessionsAuto('0点定时');
    scheduleNextDailySessionRun();          // 重新排到下一天
  }, wait);
  if (dailySessionTimer.unref) dailySessionTimer.unref();   // 不阻止进程退出（测试/脚本友好）
  console.log(`[每日签到自动生成] 下次执行：${new Date(Date.now() + wait).toLocaleString('zh-CN')}（每天 0 点）`);
}

function startDailySessionScheduler() {
  // 启动即补一次当天（服务在 0 点没运行时也能有当天场次；幂等）
  runDailySessionsAuto('启动补发').then(() => scheduleNextDailySessionRun());
  return { msUntilNextMidnight: msUntilNextMidnight2 };
}


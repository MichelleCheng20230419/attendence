// POST /api/students —— 单个添加学生
// body: { studentNo, name, classId }
// 学号重复 → 409；班级不存在 / 字段缺失 → 400
// ------------------------------------------------------------
router.post('/students', async (req, res, next) => {
  try {
    const studentNo = String(req.body.studentNo ?? '').trim();
    const name = String(req.body.name ?? '').trim();
    const classId = Number(req.body.classId);

    if (!studentNo) {
      return res.status(400).json({ error: '学号不能为空' });
    }
    if (studentNo.length > 20) {
      return res.status(400).json({ error: '学号长度不能超过 20 个字符' });
    }
    if (!name) {
      return res.status(400).json({ error: '姓名不能为空' });
    }
    if (!Number.isInteger(classId)) {
      return res.status(400).json({ error: '必须选择班级' });
    }

    const cls = await pool.query('SELECT id FROM classes WHERE id = $1', [classId]);
    if (cls.rowCount === 0) {
      return res.status(400).json({ error: '所选班级不存在' });
    }

    let insertRes;
    try {
      insertRes = await pool.query(
        `INSERT INTO students (student_no, name, class_id)
         VALUES ($1, $2, $3)
         RETURNING id`,
        [studentNo, name, classId]
      );
    } catch (e) {
      if (e.code === '23505') {
        // 学号已存在：若为已删除(软删除)状态则重新启用，否则报重复
        const ex = await pool.query(
          'SELECT id, is_active FROM students WHERE student_no = $1',
          [studentNo]
        );
        if (ex.rowCount > 0 && !ex.rows[0].is_active) {
          // 软删除的学生重新导入 → 复活（清空 deleted_at，状态回到在读）
          await pool.query(
            `UPDATE students SET is_active = true, status = '在读', deleted_at = NULL, name = $2, class_id = $3
              WHERE id = $1`,
            [ex.rows[0].id, name, classId]
          );
          insertRes = { rows: [{ id: ex.rows[0].id }] };
        } else {
          return res.status(409).json({ error: `学号 ${studentNo} 已存在，不能重复添加` });
        }
      } else {
        throw e;
      }
    }

    // 更新档案字段
    await applyStudentProfile(insertRes.rows[0].id, req.body);

    // 返回完整学生信息（含班级名）
    const { rows } = await pool.query(
      `SELECT s.id, s.student_no, s.name, s.class_id, c.class_name
         FROM students s
         LEFT JOIN classes c ON c.id = s.class_id
        WHERE s.id = $1`,
      [insertRes.rows[0].id]
    );
    const r = rows[0];
    res.status(201).json({
      student: {
        id: r.id,
        studentNo: r.student_no,
        name: r.name,
        classId: r.class_id,
        className: r.class_name || null,
      },
    });
  } catch (err) {
    next(err);
  }
});


// GET /api/students/export —— 按时间段导出考勤数据 Excel
// 参数：startDate, endDate（YYYY-MM-DD），classId（可选），fields（可选，逗号分隔）
// fields: student(学号/姓名/班级), status(签到状态), time(签到时间), reason(请假事由)
// 规则：范围内每天一个场次 → 每个学生一行；无记录显示"未签到"；按日期升序
// ------------------------------------------------------------
async function handleAttendanceExport(req, res, next) {
  try {
    const start = String(req.query.startDate || '');
    const end = String(req.query.endDate || '');
    if (!/^\d{4}-\d{2}-\d{2}$/.test(start) || !/^\d{4}-\d{2}-\d{2}$/.test(end)) {
      return res.status(400).json({ error: '日期格式应为 YYYY-MM-DD' });
    }
    const startTs = new Date(start + 'T00:00:00');
    const endTs = new Date(end + 'T23:59:59.999');
    if (isNaN(startTs.getTime()) || startTs > endTs) {
      return res.status(400).json({ error: '日期范围无效（开始日期不能晚于结束日期）' });
    }
    if (Math.round((endTs - startTs) / 86400000) > 366) {
      return res.status(400).json({ error: '导出范围不能超过 366 天' });
    }

    const classId = req.query.classId ? Number(req.query.classId) : null;
    if (classId !== null && !Number.isInteger(classId)) {
      return res.status(400).json({ error: '班级参数无效' });
    }

    const fields = String(req.query.fields || 'student,status,time,reason,method')
      .split(',').map((s) => s.trim())
      .filter((f) => ['student', 'status', 'time', 'reason', 'method'].includes(f));
    if (fields.length === 0) {
      return res.status(400).json({ error: '请至少勾选一项导出内容' });
    }
    const includeStudent = fields.includes('student');
    const includeStatus = fields.includes('status');
    const includeTime = fields.includes('time');
    const includeReason = fields.includes('reason');
    const includeMethod = fields.includes('method');

    // 学生（可按班级过滤，仅 active）
    const studentsRes = await pool.query(
      `SELECT s.id, s.student_no, s.name, c.class_name
         FROM students s
         LEFT JOIN classes c ON c.id = s.class_id
        WHERE s.is_active = true${classId !== null ? ' AND s.class_id = $1' : ''}
        ORDER BY s.student_no`,
      classId !== null ? [classId] : []
    );

    // 范围内场次，按本地日期分组取每天最新一场
    const sessionsRes = await pool.query(
      `SELECT id, start_time, auto_generated, slot, session_date FROM attendance_sessions
        WHERE start_time >= $1 AND start_time <= $2
        ORDER BY id`,
      [startTs, endTs]
    );
    // 分组键：
    //   · 老场次 → 按"天"（同一天多场只取最新一场，保持原有"每天每生一行"的口径不变）
    //   · 每天自动签到（v35）→ 按"天 + 时段"（早自习/晚自修各一行；否则导出会把早自习悄悄丢掉）
    const byDate = new Map();
    for (const s of sessionsRes.rows) {
      const d = fmtDateKey(new Date(s.start_time));
      const key = s.auto_generated ? `${d}|${s.slot || ''}` : d;
      byDate.set(key, s); // 后到 id 更大 → 保留最新
    }
    const sessionIds = [...byDate.values()].map((s) => s.id);
    const hasAuto = sessionsRes.rows.some((s) => s.auto_generated);

    const recMap = {};
    if (sessionIds.length > 0) {
      const recs = await pool.query(
        `SELECT session_id, student_id, status, leave_reason, checkin_time, check_in_method, column_index
           FROM attendance_records
          WHERE session_id = ANY($1)`,
        [sessionIds]
      );
      for (const r of recs.rows) {
        if (!recMap[r.session_id]) recMap[r.session_id] = {};
        recMap[r.session_id][r.student_id] = r;
      }
    }

    const STATUS_CN = { present: '已签到', leave: '请假', late: '迟到', absent: '缺勤' };
    const REASON_CN = { sick: '病假', personal: '事假', official: '公假' };
    const METHOD_CN = { manual: '手动', batch_all: '全员签到', batch_column: '按列签到', makeup: '补签', save_all: '整场保存', batch_leave: '批量请假' };

    const dates = [...byDate.keys()].sort(); // 日期升序（auto 场次键为 "日期|时段"）
    const rows = [];
    for (const d of dates) {
      const sess = byDate.get(d);
      const dayOnly = d.split('|')[0];
      const recs = recMap[sess.id] || {};
      for (const stu of studentsRes.rows) {
        const rec = recs[stu.id];
        const row = {};
        if (includeStudent) {
          row['学号'] = stu.student_no;
          row['姓名'] = stu.name;
          row['班级'] = stu.class_name || '';
        }
        row['日期'] = dayOnly;
        // 只有范围内存在"每天自动签到"时才加「时段」列 —— 老数据导出列完全不变（兼容既有用例/习惯）
        if (hasAuto) {
          row['时段'] = sess.slot === 'morning' ? '早自习' : (sess.slot === 'evening' ? '晚自修' : '');
        }
        if (includeStatus) {
          row['签到状态'] = rec ? (STATUS_CN[rec.status] || rec.status) : '未签到';
        }
        if (includeTime) {
          row['签到时间'] = rec && rec.checkin_time ? fmtHMS(rec.checkin_time) : '-';
        }
        if (includeMethod) {
          row['签到方式'] = rec ? (METHOD_CN[rec.check_in_method] || rec.check_in_method) : '-';
        }
        if (includeReason) {
          row['请假事由'] = rec && rec.leave_reason ? (REASON_CN[rec.leave_reason] || rec.leave_reason) : '-';
        }
        rows.push(row);
      }
    }

    if (rows.length === 0) {
      return res.status(404).json({ error: '该时间段内没有签到数据' });
    }

    const wb = XLSX.utils.book_new();
    const ws = XLSX.utils.json_to_sheet(rows);
    const colOrder = [];
    if (includeStudent) colOrder.push('学号', '姓名', '班级');
    colOrder.push('日期');
    if (includeStatus) colOrder.push('签到状态');
    if (includeTime) colOrder.push('签到时间');
    if (includeMethod) colOrder.push('签到方式');
    if (includeReason) colOrder.push('请假事由');
    ws['!cols'] = colOrder.map((h) => ({
      wch: h === '学号' ? 12 : h === '班级' ? 14 : h === '签到时间' ? 12 : h === '签到方式' ? 10 : h === '日期' ? 12 : 10,
    }));
    XLSX.utils.book_append_sheet(wb, ws, '签到数据');

    const buf = XLSX.write(wb, { type: 'buffer', bookType: 'xlsx' });
    const fn = `考勤数据_${start}_至_${end}${classId !== null ? '_班级' + classId : ''}.xlsx`;
    res.setHeader(
      'Content-Type',
      'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet'
    );
    res.setHeader('Content-Disposition', `attachment; filename*=UTF-8''${encodeURIComponent(fn)}`);
    res.send(buf);
  } catch (err) {
    next(err);
  }
}


// POST /api/attendance/records/batch —— 独立补签页批量补签
// body: { sessionId?, planId?, studentIds: [..], status? }（status 默认 present）
//  - sessionId 与 planId 至少其一：手动场次用 sessionId；
//    已结束计划若从未生成过场次（如服务器离线错过触发），可只传 planId，
//    后端会按计划日期/时间自动补录一个 closed 场次再写入记录（事务+行锁防重复）
//  - 仅管理员/教师可用（学生/班长 403）
//  - 已签到(present/late)与请假(leave)的学生会被跳过，绝不覆盖
//  - 只有"未签 / 缺勤"的学生会被补写为已签到
//  - 每条记录标记 check_in_method = 'makeup'（区别于正常签到），写入操作日志
// ------------------------------------------------------------
router.post('/attendance/records/batch', async (req, res, next) => {
  try {
    const role = req.session.user.role;
    if (role === 'student' || role === 'monitor') {
      return res.status(403).json({ error: '无权限：学生/班长不能进行补签操作' });
    }
    let sessionId = Number(req.body.sessionId);
    if (!Number.isInteger(sessionId) || sessionId <= 0) sessionId = null;
    const planParam = Number(req.body.planId);
    const planIdNum = Number.isInteger(planParam) && planParam > 0 ? planParam : null;

    let studentIds = Array.isArray(req.body.studentIds) ? req.body.studentIds : [];
    studentIds = [...new Set(studentIds.map(Number).filter((x) => Number.isInteger(x) && x > 0))];
    if (studentIds.length === 0) {
      return res.status(400).json({ error: '请至少选择一名学生' });
    }
    if (studentIds.length > 500) {
      return res.status(400).json({ error: '单次补签不能超过 500 人' });
    }
    const status = String(req.body.status || 'present').trim();
    if (status !== 'present') {
      return res.status(400).json({ error: '批量补签仅支持标记为已签到(present)' });
    }

    // 教师：只能补签自己班级的在读学生
    let myClassId = null;
    if (role === 'teacher') {
      const me = await pool.query('SELECT class_id FROM users WHERE id = $1', [req.session.user.id]);
      myClassId = (me.rows[0] && me.rows[0].class_id) || null;
      if (!myClassId) return res.status(400).json({ error: '当前教师账号未绑定班级，无法补签' });
    }

    // ---------- 解析目标场次 ----------
    let planMeta = null; // 计划存在但尚未生成场次 → 需要自动补录
    if (!sessionId) {
      // 计划路径：只传 planId（已结束但未生成过场次的计划）
      if (!planIdNum) {
        return res.status(400).json({ error: '缺少有效的 sessionId 或 planId' });
      }
      const pRes = await pool.query(
        `SELECT id, status, session_id, class_id, plan_date, start_time, duration_minutes,
                created_by, created_by_name, created_by_role
           FROM attendance_plans
          WHERE id = $1`,
        [planIdNum]
      );
      if (pRes.rowCount === 0) {
        return res.status(404).json({ error: '签到计划不存在' });
      }
      const pl = pRes.rows[0];
      if (pl.status !== 'ended') {
        return res.status(400).json({ error: '仅已结束的签到计划可以补签' });
      }
      if (role === 'teacher' && pl.class_id && Number(pl.class_id) !== myClassId) {
        return res.status(403).json({ error: '该计划属于其他班级，您只能补签本班计划' });
      }
      if (pl.session_id) {
        sessionId = pl.session_id;
      } else {
        planMeta = pl;
      }
    }

    // 手动/场次路径：场次必须存在，且对本账号可见（统一鉴权：别的班场次一律 403）
    // 计划路径也可能落到"别的班的场次"上：方案 A 下「全部班级」计划会**按班拆成多场**，
    //   attendance_plans.session_id 只是"代表场次"（可能是别的班那一场）→
    //   教师补签时改为取【本班那条关联场次】(attendance_plan_sessions.class_id = 本班)
    if (!planMeta) {
      let guard = await assertSessionVisible(req.session.user, sessionId, { classId: req.body.classId });
      if (!guard.ok && role === 'teacher' && myClassId && planIdNum) {
        const alt = await pool.query(
          `SELECT aps.session_id
             FROM attendance_plan_sessions aps
             JOIN attendance_sessions s ON s.id = aps.session_id
            WHERE aps.plan_id = $1 AND aps.class_id = $2
            ORDER BY aps.id DESC LIMIT 1`,
          [planIdNum, myClassId]
        );
        if (alt.rowCount > 0 && Number(alt.rows[0].session_id) !== Number(sessionId)) {
          sessionId = alt.rows[0].session_id;
          guard = await assertSessionVisible(req.session.user, sessionId, {});
        }
      }
      if (!guard.ok) return res.status(guard.status || 403).json({ error: guard.error });
    }

    // 计划未生成场次 → 按计划日期/时间自动补录 closed 场次（事务 + 行锁防并发重复）
    if (planMeta) {
      // 补录场次同样要带班级归属（方案 A：新建场次 class_id 不允许为空）：
      //   计划指定班级 → 该班；「全部班级」计划 → 教师按自己所带班级补录（管理员为全校 NULL）
      const recClassId = planMeta.class_id
        ? Number(planMeta.class_id)
        : (role === 'teacher' ? myClassId : null);
      const client = await pool.connect();
      try {
        await client.query('BEGIN');
        const lockRes = await client.query(
          'SELECT session_id FROM attendance_plans WHERE id = $1 FOR UPDATE',
          [planIdNum]
        );
        if (lockRes.rows[0] && lockRes.rows[0].session_id) {
          sessionId = lockRes.rows[0].session_id; // 已被并发请求补录
        } else {
          const dur = Math.max(Number(planMeta.duration_minutes) || 10, 1);
          const dStr = fmtDate(planMeta.plan_date);
          const tStr = String(planMeta.start_time).slice(0, 8);
          const ins = await client.query(
            `INSERT INTO attendance_sessions
               (start_time, deadline, status, created_by, created_by_name, created_by_role, start_source, deadline_minutes, class_id)
             SELECT ($1::date + $2::time),
                    ($1::date + $2::time) + make_interval(mins => $3::int),
                    'closed', $4, $5, $6, 'plan', $3::int, $7
             RETURNING id`,
            [dStr, tStr, dur, planMeta.created_by || null, planMeta.created_by_name || null,
              planMeta.created_by_role || null, recClassId]
          );
          sessionId = ins.rows[0].id;
          // 计划指定了班级 → 该场次就是这个计划的代表场次；「全部班级」计划 → 只建关联行，不动代表场次
          if (planMeta.class_id) {
            await client.query(
              'UPDATE attendance_plans SET session_id = $2 WHERE id = $1',
              [planIdNum, sessionId]
            );
          }
          if (recClassId) {
            await client.query(
              `INSERT INTO attendance_plan_sessions (plan_id, session_id, class_id) VALUES ($1, $2, $3)
               ON CONFLICT (plan_id, session_id) DO NOTHING`,
              [planIdNum, sessionId, recClassId]
            );
          }
        }
        await client.query('COMMIT');
      } catch (e) {
        await client.query('ROLLBACK');
        throw e;
      } finally {
        client.release();
      }
    }

    // ---------- 学生校验（在读 + 教师限本班）----------
    let classFilter = '';
    const qp = [];
    if (role === 'teacher') {
      classFilter = ' AND class_id = $2';
      qp.push(myClassId);
    }
    const stuRes = await pool.query(
      `SELECT id FROM students
        WHERE id = ANY($1::int[]) AND is_active = true AND status = '在读'` + classFilter,
      [studentIds].concat(qp)
    );
    const validIds = stuRes.rows.map((r) => r.id);
    if (validIds.length !== studentIds.length) {
      const missing = studentIds.filter((x) => !validIds.includes(x));
      return res.status(403).json({
        error: role === 'teacher'
          ? '包含非本班在读学生，无法补签（请仅选择本班学生）'
          : '包含不存在/非在读的学生，无法补签',
        invalidIds: missing,
      });
    }

    // ---------- 跳过已签到/请假：只对"未签或缺勤"补签 ----------
    const skipRes = await pool.query(
      `SELECT student_id, status FROM attendance_records
        WHERE session_id = $1 AND student_id = ANY($2::int[])`,
      [sessionId, validIds]
    );
    const SKIP = new Set(['present', 'late', 'leave']);
    const skippedIds = new Set();
    const todoIds = [];
    for (const r of skipRes.rows) {
      if (SKIP.has(r.status)) skippedIds.add(r.student_id);
    }
    for (const id of validIds) {
      if (!skippedIds.has(id)) todoIds.push(id);
    }

    let updated = 0;
    for (const sid of todoIds) {
      const { rowCount } = await pool.query(
        `INSERT INTO attendance_records (session_id, student_id, status, leave_reason, checkin_time, check_in_method)
         VALUES ($1, $2, 'present', NULL, now(), 'makeup')
         ON CONFLICT (session_id, student_id) DO UPDATE
           SET status = 'present',
               leave_reason = NULL,
               checkin_time = now(),
               check_in_method = 'makeup'`,
        [sessionId, sid]
      );
      updated += rowCount;
    }
    await logOperation(req, 'batch_makeup', {
      sessionId,
      planId: planIdNum || null,
      autoCreatedSession: !!planMeta,
      count: updated,
      skipped: skippedIds.size,
      status,
      method: 'makeup',
    });
    res.json({
      ok: true,
      count: updated,
      skipped: skippedIds.size,
      method: 'makeup',
      sessionId,
      autoCreatedSession: !!planMeta,
    });
  } catch (err) {
    next(err);
  }
});

function fmtPlanDate(d) {
  const p = (n) => String(n).padStart(2, '0');
  return `${d.getFullYear()}-${p(d.getMonth() + 1)}-${p(d.getDate())}`;
}

// 按周循环生成日期列表
function genWeeklyDates(weekdays, dateFrom, dateTo) {
  const out = [];
  const p = (n) => String(n).padStart(2, '0');
  const start = new Date(String(dateFrom) + 'T00:00:00');
  const end = dateTo ? new Date(String(dateTo) + 'T00:00:00') : new Date(start);
  if (isNaN(start.getTime())) return out;
  const wd = new Set(weekdays.map(Number));
  const d = new Date(start);
  while (d <= end) {
    if (wd.has(d.getDay())) {
      out.push(`${d.getFullYear()}-${p(d.getMonth() + 1)}-${p(d.getDate())}`);
    }
    d.setDate(d.getDate() + 1);
  }
  return out;
}


// 自动触发定时任务：每分钟检查一次
//  1) 到点计划 → 创建签到场次 + 计划状态 pending→active/ended（事务原子）
//     场次时间一律使用【计划中设定的时间】：
//       start_time = plan_date + start_time（如 08:00）
//       deadline   = start_time + duration_minutes（如 08:10）
//     若触发时计划窗口已过（服务器离线导致晚触发）：按计划时间补建
//     closed 场次并补缺勤，计划直接置 ended（可用"补签"修正出勤）
//     过期宽限：超过 2 小时未触发的计划不再补发起，直接标记 ended（过期跳过）
//  2) 场次截止时间已过 → 补缺勤 + 计划状态 active→ended
//  3) 修复：计划已 active 但关联场次缺失/已关闭（异常状态）→ 窗口内自动重建
//     （重建同样使用计划时间）
// 每个计划独立 try/catch，单个失败不影响其他计划
// ------------------------------------------------------------
const TRIGGER_GRACE_MS = 2 * 60 * 60 * 1000; // 触发宽限：2 小时

// 触发到点的 pending 计划（幂等：WHERE status='pending' 防并发重复）
// 计划的目标班级：
//   · 计划指定了班级 → 只给该班发场次
//   · 计划未指定班级（历史上"全部班级"计划）→ 按班拆场：所有有在读学生的班级各一场
//     （不再建 class_id IS NULL 的"全校场次"，否则所有班都会看到同一场签到）
async function planTargetClassIds(classId) {
  const cid = Number(classId);
  if (Number.isInteger(cid) && cid > 0) return [cid];
  const { rows } = await pool.query(
    `SELECT DISTINCT class_id FROM students
      WHERE is_active = true AND status = '在读' AND class_id IS NOT NULL
      ORDER BY class_id`
  );
  return rows.map((r) => r.class_id);
}

// 触发到点的签到计划（scheduler 每分钟调用一次；GET /attendance/status 也会幂等调用）
//   opts.onlyPlanId：仅供测试定向触发某条计划（生产调用不传 → 处理全部 pending 计划）
async function triggerDuePlans(opts = {}) {
  const onlyId = Number(opts && opts.onlyPlanId);
  const due = Number.isInteger(onlyId) && onlyId > 0
    ? await pool.query(
        "SELECT id, plan_date, start_time, duration_minutes, created_by, created_by_name, created_by_role, class_id FROM attendance_plans WHERE status = 'pending' AND id = $1",
        [onlyId]
      )
    : await pool.query(
        "SELECT id, plan_date, start_time, duration_minutes, created_by, created_by_name, created_by_role, class_id FROM attendance_plans WHERE status = 'pending'"
      );
  for (const p of due.rows) {
    try {
      const startTs = new Date(`${fmtPlanDate(p.plan_date)}T${String(p.start_time).slice(0, 5)}`);
      const deadlineTs = new Date(startTs.getTime() + p.duration_minutes * 60000);
      const now = Date.now();
      if (startTs.getTime() > now) continue; // 还没到时间

      // 超过宽限期：不补发起，标记过期结束
      if (now - startTs.getTime() > TRIGGER_GRACE_MS) {
        await pool.query(
          `UPDATE attendance_plans SET status = 'ended' WHERE id = $1 AND status = 'pending'`,
          [p.id]
        );
        console.log(`[计划过期跳过] 计划#${p.id}（${fmtPlanDate(p.plan_date)} ${String(p.start_time).slice(0, 5)}）已超宽限期，不补发起`);
        continue;
      }

      // 计划窗口是否已过（晚触发：服务器离线错过时间点）
      const windowPassed = now > deadlineTs.getTime();

      // 【不抢占 / 共用】已有进行中的场次且尚未到截止时间
      //   旧实现：先 finalizeAbsent + 关闭该场次，再新建 —— 老师正在登记的场次被强行结束，
      //   页面上"已签到"的记录随场次切换全部消失，截止后新场次补缺勤 →
      //   表现为"我明明签到了，怎么变成全体缺勤"（同时两个班的同点计划会互相顶掉，
      //   每分钟新建一场，产生大量"全员缺勤"幽灵场次）。
      //   现行规则（系统同时只保留一个进行中场次）：
      //     · 进行中的是【计划场次】且本计划还在窗口内 → 两个班的同点计划共用这一场（不改任何记录）
      //     · 进行中的是【人工发起】场次 → 本次计划不抢占（保持 pending，稍后或过期处理）
      //     · 本计划窗口已过 → 不补建"全体缺勤"的幽灵场次，直接标记 ended
      // 【逐班解析】每个班只看"自己班"的进行中场次（方案 A：场次归属 = class_id）
      //   · 全校计划（plan.class_id IS NULL）→ 按班拆场，每班各一场，绝不共用一个场次
      const targetClasses = await planTargetClassIds(p.class_id);
      if (targetClasses.length === 0) {
        await pool.query(`UPDATE attendance_plans SET status = 'ended' WHERE id = $1 AND status = 'pending'`, [p.id]);
        console.log(`[计划跳过] 计划#${p.id}：没有可发起签到的班级（无在读学生）`);
        continue;
      }
      const shareMap = new Map();        // classId → 复用的进行中计划场次
      const blockedClasses = [];         // 该班正在"人工签到"→ 本计划不抢占该班（其余班照常）
      for (const cid of targetClasses) {
        const running = await activeSessionFor(cid);
        if (running && new Date(running.deadline) > new Date()) {
          if (running.start_source === 'plan') shareMap.set(cid, running);
          else blockedClasses.push({ classId: cid, sessionId: running.id });
        }
      }
      // 全部目标班级都被进行中的场次占用 → 本计划保持 pending，下一轮再试；
      //   **若本计划窗口已过**（例如全班整天都有"每天自动签到"场次）→ 直接置 ended，
      //   否则计划管理里会积压一堆永远"待签到"、也不会再发起的僵尸计划。
      if (blockedClasses.length === targetClasses.length) {
        if (windowPassed) {
          await pool.query(`UPDATE attendance_plans SET status = 'ended' WHERE id = $1 AND status = 'pending'`, [p.id]);
          console.log(`[计划结束] 计划#${p.id}：${targetClasses.length} 个班均有进行中的签到（${blockedClasses.map((x) => x.classId).join(',')}），窗口已过 → 置为已结束`);
        } else {
          console.log(`[计划触发跳过] 计划#${p.id}：${targetClasses.length} 个班均有进行中的签到，不抢占（窗口内继续等待）`);
        }
        continue;
      }
      if (blockedClasses.length) {
        console.log(`[计划部分跳过] 计划#${p.id}：班级 ${blockedClasses.map((x) => x.classId).join(',')} 正在人工签到，本次不为这些班建场次（其余班照常按班拆场）`);
      }
      if (windowPassed) {
        await pool.query(
          `UPDATE attendance_plans SET status = 'ended' WHERE id = $1 AND status = 'pending'`,
          [p.id]
        );
        console.log(`[计划错过] 计划#${p.id}（${String(p.start_time).slice(0, 5)}）窗口已过且无进行中场次，不补建场次（避免写入全体缺勤）`);
        continue;
      }
      // 目标班级里"已过截止时间但仍是 active"的残留场次：先补缺勤并关闭（按班级收尾，不动别班的场次）
      for (const cid of targetClasses) {
        if (shareMap.has(cid)) continue;
        const stale = await activeSessionFor(cid);
        // v35：每天自动签到（早/晚）场次**不限时**，不参与"过期 residual 收尾"（由次日 0 点统一收口）
        if (stale && !stale.auto_generated && new Date(stale.deadline) <= new Date()) {
          await finalizeAbsent(stale.id);
          await pool.query(`UPDATE attendance_sessions SET status = 'closed' WHERE id = $1 AND status = 'active'`, [stale.id]);
          console.log(`[计划收尾] 计划#${p.id}：班级#${cid} 的残留场次#${stale.id} 已截止，已补缺勤并关闭`);
        }
      }

      // 事务：抢占计划 + 逐班创建/共用场次 + 计划状态流转（原子，避免中间态）
      const client = await pool.connect();
      const createdSessions = [];   // [{ sessionId, classId }]
      let representativeId = null;
      try {
        await client.query('BEGIN');
        const claim = await client.query(
          `UPDATE attendance_plans SET status = 'active' WHERE id = $1 AND status = 'pending'`,
          [p.id]
        );
        if (claim.rowCount === 0) {
          await client.query('ROLLBACK'); // 已被并发处理
        } else {
          // 场次时间 = 计划设定时间（start_time=计划时间，deadline=计划时间+时长）
          // 来源标记为 plan，并把计划的创建人作为"发起人"记录（可追溯）
          for (const cid of targetClasses) {
            if (blockedClasses.some((x) => x.classId === cid)) continue;   // 该班正在人工签到 → 不动
            const shared = shareMap.get(cid);
            if (shared) {
              await client.query(
                `INSERT INTO attendance_plan_sessions (plan_id, session_id, class_id) VALUES ($1, $2, $3)
                 ON CONFLICT (plan_id, session_id) DO NOTHING`,
                [p.id, shared.id, cid]
              );
              if (!representativeId) representativeId = shared.id;
              continue;
            }
            const s = await client.query(
              `INSERT INTO attendance_sessions
                 (start_time, deadline, status, created_by, created_by_name, created_by_role, start_source, deadline_minutes, class_id)
               VALUES ($1, $2, 'active', $3, $4, $5, 'plan', $6, $7)
               RETURNING id`,
              [startTs, deadlineTs, p.created_by || null, p.created_by_name || null, p.created_by_role || null,
                Number(p.duration_minutes) || null, cid]
            );
            await client.query(
              `INSERT INTO attendance_plan_sessions (plan_id, session_id, class_id) VALUES ($1, $2, $3)
               ON CONFLICT (plan_id, session_id) DO NOTHING`,
              [p.id, s.rows[0].id, cid]
            );
            createdSessions.push({ sessionId: s.rows[0].id, classId: cid });
            if (!representativeId) representativeId = s.rows[0].id;
          }
          await client.query(`UPDATE attendance_plans SET session_id = $2 WHERE id = $1`, [p.id, representativeId]);
          await client.query('COMMIT');
          const hm = (d) => String(d.getHours()).padStart(2, '0') + ':' + String(d.getMinutes()).padStart(2, '0');
          console.log(`[计划触发] 计划#${p.id}（${hm(startTs)}–${hm(deadlineTs)}）→ 按班新建 ${createdSessions.length} 场 / 共用 ${shareMap.size} 场，代表场次#${representativeId}`);
        }
      } catch (e) {
        await client.query('ROLLBACK').catch(() => {});
        throw e;
      } finally {
        client.release();
      }
      // 新建场次：提交后同步当天「全天请假」登记（finalizeAbsent 走独立连接，须在事务提交后执行）
      for (const c of createdSessions) {
        await applyDayLeaves(c.sessionId);
      }
    } catch (err) {
      console.error(`[计划触发错误] 计划#${p.id}:`, err.message);
    }
  }
}

// 修复 active 计划与会话的一致性（补偿机制）
//   opts.onlyPlanId：仅供测试定向修复某条计划（生产调用不传 → 处理全部 active 计划）
async function repairActivePlans(opts = {}) {
  const onlyId = Number(opts && opts.onlyPlanId);
  const rows = Number.isInteger(onlyId) && onlyId > 0
    ? await pool.query(
        `SELECT p.id, p.plan_date, p.start_time, p.duration_minutes, p.session_id,
                p.created_by, p.created_by_name, p.created_by_role, p.class_id
           FROM attendance_plans p
          WHERE p.status = 'active' AND p.id = $1`,
        [onlyId]
      )
    : await pool.query(
        `SELECT p.id, p.plan_date, p.start_time, p.duration_minutes, p.session_id,
                p.created_by, p.created_by_name, p.created_by_role, p.class_id
           FROM attendance_plans p
          WHERE p.status = 'active'`
      );
  for (const p of rows.rows) {
    try {
      const startTs = new Date(`${fmtPlanDate(p.plan_date)}T${String(p.start_time).slice(0, 5)}`);
      const deadlineTs = new Date(startTs.getTime() + p.duration_minutes * 60000);
      // 该计划名下的全部场次（方案 A：attendance_plan_sessions 是权威 1:N；plans.session_id 只作代表）
      const linkRows = (await pool.query(
        `SELECT aps.session_id, aps.class_id AS link_class_id, s.status, s.class_id AS sess_class_id
           FROM attendance_plan_sessions aps
           JOIN attendance_sessions s ON s.id = aps.session_id
          WHERE aps.plan_id = $1
          ORDER BY aps.id`,
        [p.id]
      )).rows;
      // 兼容历史数据：没有关联行时回退到计划上的代表场次
      if (linkRows.length === 0 && p.session_id) {
        const s = (await pool.query(
          'SELECT id, status, class_id FROM attendance_sessions WHERE id = $1', [p.session_id]
        )).rows[0];
        if (s) {
          linkRows.push({ session_id: s.id, link_class_id: s.class_id, status: s.status, sess_class_id: s.class_id });
        }
      }
      const activeLinks = linkRows.filter((r) => r.status === 'active');
      // 已过计划窗口 → 补缺勤并结束（该计划名下的所有进行中场次）
      if (Date.now() > deadlineTs.getTime()) {
        for (const r of activeLinks) {
          await finalizeAbsent(r.session_id);
          await pool.query(`UPDATE attendance_sessions SET status = 'closed' WHERE id = $1 AND status = 'active'`, [r.session_id]);
        }
        await pool.query(`UPDATE attendance_plans SET status = 'ended' WHERE id = $1`, [p.id]);
        console.log(`[计划结束] 计划#${p.id} 已结束，已补缺勤（关闭 ${activeLinks.length} 场）`);
        continue;
      }
      // 窗口内：逐班检查"计划签到中"是否都有可签场次（每班必须是自己的场次）
      const targetClasses = await planTargetClassIds(p.class_id);
      for (const cid of targetClasses) {
        const covered = activeLinks.some(
          (r) => r.link_class_id === null || r.sess_class_id === null || Number(r.link_class_id) === cid
        );
        if (covered) continue;
        const running = await activeSessionFor(cid);
        if (running && new Date(running.deadline) > new Date()) {
          if (running.start_source === 'plan') {
            // 同点计划共用这一场（同一班级内），绝不新建第二场（否则两个计划每轮互相顶掉，
            // 会每分钟产生一个"全员缺勤"的幽灵场次，并把老师已签到的场次切走）
            await pool.query(
              `INSERT INTO attendance_plan_sessions (plan_id, session_id, class_id) VALUES ($1, $2, $3)
               ON CONFLICT (plan_id, session_id) DO NOTHING`,
              [p.id, running.id, cid]
            );
            await pool.query(`UPDATE attendance_plans SET session_id = COALESCE(session_id, $2) WHERE id = $1`, [p.id, running.id]);
            console.log(`[计划修复] 计划#${p.id} 班级#${cid} 与进行中的计划场次#${running.id} 共用（不新建场次）`);
          } else {
            console.log(`[计划修复跳过] 计划#${p.id} 班级#${cid}：人工场次#${running.id} 进行中，不重建（避免抢走老师正在登记的场次）`);
          }
          continue;
        }
        const s = await pool.query(
          `INSERT INTO attendance_sessions
             (start_time, deadline, status, created_by, created_by_name, created_by_role, start_source, deadline_minutes, class_id)
           VALUES ($1, $2, 'active', $3, $4, $5, 'plan', $6, $7)
           RETURNING id`,
          [startTs, deadlineTs, p.created_by || null, p.created_by_name || null, p.created_by_role || null,
            Number(p.duration_minutes) || null, cid]
        );
        await pool.query(
          `INSERT INTO attendance_plan_sessions (plan_id, session_id, class_id) VALUES ($1, $2, $3)
           ON CONFLICT (plan_id, session_id) DO NOTHING`,
          [p.id, s.rows[0].id, cid]
        );
        await pool.query(`UPDATE attendance_plans SET session_id = COALESCE(session_id, $2) WHERE id = $1`, [p.id, s.rows[0].id]);
        // 当天登记过「全天请假」的学生，重建场次后同样直接记为请假
        await applyDayLeaves(s.rows[0].id);
        console.log(`[计划修复] 计划#${p.id} 班级#${cid} 会话缺失已重建 → 场次#${s.rows[0].id}（按计划时间 ${String(p.start_time).slice(0, 5)}）`);
      }
    } catch (err) {
      console.error(`[计划修复错误] 计划#${p.id}:`, err.message);
    }
  }
}


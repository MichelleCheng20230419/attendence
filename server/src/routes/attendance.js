// POST /api/attendance/session-save —— 「整场保存」（v35 · 路线 B 的核心写入路径）
// body: {
//   sessionId,
//   records: [{ studentId, status: 'present'|'absent'|'leave', leaveReason? }, ...],  // 通常=全班名册
//   classId?   // 全校场次（class_id IS NULL）时必须显式给班级，避免写到别的班
// }
// 语义（与老师确认的"默认全签 + 只取消未到 + 点保存即录入"一致）：
//   · 前端进页面时**默认全绿**（不发请求）；点「保存」时把**整场**写库 —— 没被点掉的是 present，
//     被点掉的是 absent，右键标记的是 leave。→ 落库的仍是"显式登记"，统计口径与历史连续（路线 B）
//   · 幂等：ON CONFLICT (session_id, student_id) DO UPDATE（同一场次反复保存只覆盖不改行数）
//   · 当天「全天请假」优先：登记过全天请假的学生，即使前端传 present 也写 leave（与既有"请假不被覆盖"一致）
//   · 不限时：auto 场次任何时间都能保存；老场次保持"截止后不可写"（与 /attendance/checkin 一致）
//   · 权限：与其它写入接口同一套（班长/教师限本班；管理员按 ?classId=/绑定班级）
// ------------------------------------------------------------
router.post('/attendance/session-save', async (req, res, next) => {
  try {
    // 学生账号只读（与 /attendance/checkin 一致）
    if (req.session.user.role === 'student') {
      return res.status(403).json({ error: '无权限：学生账号只读' });
    }
    const sid = Number(req.body.sessionId);
    if (!Number.isInteger(sid) || sid <= 0) return res.status(400).json({ error: '缺少有效的 sessionId' });
    const list = Array.isArray(req.body.records) ? req.body.records : null;
    if (!list || list.length === 0) return res.status(400).json({ error: 'records 不能为空（请提交整场学生状态）' });
    if (list.length > 2000) return res.status(400).json({ error: 'records 过多（单场最多 2000 人）' });

    const guard = await assertSessionVisible(req.session.user, sid, { classId: req.body.classId });
    if (guard.error) return res.status(guard.status || 403).json({ error: guard.error });
    const session = await pool.query(`SELECT ${SESSION_SELECT_COLS} FROM attendance_sessions WHERE id = $1`, [sid]);
    const s = session.rows[0];
    if (!s) return res.status(404).json({ error: '场次不存在' });
    if (s.status !== 'active') return res.status(400).json({ error: '该场次已结束，不能保存（可在考勤分析中查看）' });
    if (!s.auto_generated && new Date() > new Date(s.deadline)) {
      await finalizeAbsent(s.id);
      return res.status(400).json({ error: '签到窗口已关闭' });
    }

    // 场次范围内的学生名册（全校场次=指定班级；班级场次=该班）
    const classId = s.class_id || Number(req.body.classId) || null;
    if (!s.auto_generated && !s.class_id && !classId) {
      return res.status(400).json({ error: '全校场次请指定 classId 后再保存' });
    }
    const roster = (await pool.query(
      `SELECT id FROM students
        WHERE is_active = true AND status = '在读'
          AND ($1::int IS NULL OR class_id = $1)`,
      [classId]
    )).rows.map((r) => r.id);
    const rosterSet = new Set(roster);

    // 当天全天请假（登记优先，与 applyDayLeaves / finalizeAbsent 口径一致）
    const dlRows = (await pool.query(
      `SELECT dl.student_id, dl.reason FROM student_day_leaves dl
        WHERE dl.leave_date = (SELECT (start_time)::date FROM attendance_sessions WHERE id = $1)
          AND ($2::int IS NULL OR dl.student_id = ANY($3::int[]))`,
      [sid, null, roster.length ? roster : [0]]
    )).rows;
    const dayLeave = new Map(dlRows.map((r) => [r.student_id, r.reason]));

    const VALID = new Set(['present', 'absent', 'leave']);
    const invalid = [];
    const rows = [];
    const seen = new Set();
    for (const item of list) {
      const studentId = Number(item && item.studentId);
      const status = String((item && item.status) || '').trim();
      if (!Number.isInteger(studentId) || !rosterSet.has(studentId)) { invalid.push({ studentId: item && item.studentId, reason: 'not-in-class' }); continue; }
      if (!VALID.has(status)) { invalid.push({ studentId, reason: 'bad-status' }); continue; }
      let finalStatus = status;
      let reason = null;
      if (dayLeave.has(studentId)) { finalStatus = 'leave'; reason = dayLeave.get(studentId); }
      else if (status === 'leave') {
        reason = LEAVE_CODES.has(String(item.leaveReason || '')) ? String(item.leaveReason) : 'personal';
      }
      if (seen.has(studentId)) { invalid.push({ studentId, reason: 'duplicate' }); continue; }
      seen.add(studentId);
      rows.push([studentId, finalStatus, reason]);
    }
    if (rows.length === 0) return res.status(400).json({ error: '没有可保存的有效记录', invalid });

    let saved = 0;
    await pool.query('BEGIN');
    try {
      for (const [studentId, status, reason] of rows) {
        const r = await pool.query(
          `INSERT INTO attendance_records (session_id, student_id, status, leave_reason, checkin_time, check_in_method)
           VALUES ($1, $2, $3, $4, now(), 'save_all')
           ON CONFLICT (session_id, student_id) DO UPDATE
             SET status = EXCLUDED.status,
                 leave_reason = EXCLUDED.leave_reason,
                 checkin_time = now(),
                 check_in_method = 'save_all'`,
          [sid, studentId, status, reason]
        );
        saved += r.rowCount;
      }
      // 名册里"没有出现在提交列表里"的学生不写（保持未登记），避免误伤转学/新增
      await pool.query('COMMIT');
    } catch (e) {
      await pool.query('ROLLBACK').catch(() => {});
      throw e;
    }

    const counts = { present: 0, absent: 0, leave: 0 };
    for (const [, status] of rows.map((r) => [r[0], r[1]])) counts[status] += 1;
    await logOperation(req, 'session_save', {
      sessionId: sid, classId, saved, roster: roster.length, counts,
      autoGenerated: s.auto_generated === true, slot: s.slot || null, invalid: invalid.length,
    });
    res.json({
      ok: true, sessionId: sid, saved, rosterSize: roster.length, counts,
      invalid, autoGenerated: s.auto_generated === true, slot: s.slot || null, slotLabel: slotLabelOf(s),
    });
  } catch (err) {
    next(err);
  }
});


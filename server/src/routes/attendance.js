// 批量签到公共逻辑：按模式取出目标学生并写入记录
async function batchCheckinCore(req, res, next) {
  const { mode, columnIndex, checkInMethod } = req.body || {};
  const role = req.session.user.role;
  if (role === 'student') {
    return res.status(403).json({ error: '无权限：学生账号不可操作签到' });
  }
  // 统一班级解析：教师/班长只能操作自己所带的班；管理员必须显式选择班级
  const viewer = await viewerScope(req.session.user, req.body.classId);
  if (viewer.error) return res.status(viewer.status || 400).json({ error: viewer.error });
  if (viewer.isAdmin && viewer.schoolWideView) {
    return res.status(400).json({ error: '请先选择要批量签到的班级（管理员可先点「查看班级」选一个班）' });
  }
  const me = await pool.query('SELECT class_id FROM users WHERE id = $1', [req.session.user.id]);
  const userClassId = (me.rows[0] && me.rows[0].class_id) || null;
  const requested = Number(req.body.classId) || viewer.displayClassId || userClassId;
  if (!requested) {
    return res.status(400).json({
      error: viewer.isAdmin ? '请先选择要批量签到的班级' : '当前账号未绑定班级，无法批量签到',
    });
  }
  if (!viewer.schoolWideView && !viewer.classIds.includes(Number(requested))) {
    return res.status(403).json({ error: '无权限：你不是该班级的教师或班长' });
  }
  const classId = Number(requested);
  // 场次 = 该班当前进行中的场次（优先本班专属，其次全校场次）
  //   v35（早/晚两场）：可显式传 sessionId 指定场次（否则"最新一场"会把早自习的批量操作记到晚自修）
  let session = null;
  const wantSid2 = Number(req.body.sessionId);
  if (Number.isInteger(wantSid2) && wantSid2 > 0) {
    const guardS = await assertSessionVisible(req.session.user, wantSid2, { classId });
    if (guardS.error) return res.status(guardS.status || 403).json({ error: guardS.error });
    session = (await pool.query(`SELECT ${SESSION_SELECT_COLS} FROM attendance_sessions WHERE id = $1`, [wantSid2])).rows[0] || null;
    if (!session) return res.status(404).json({ error: '签到场次不存在' });
    if (session.status !== 'active') {
      return res.status(400).json({ error: '该场次已结束，不能批量签到' });
    }
    if (session.class_id !== null && session.class_id !== classId) {
      return res.status(403).json({ error: '无权限：该场次不属于本班' });
    }
  } else {
    session = await activeSessionFor(classId);
  }
  if (!session) {
    return res.status(400).json({ error: '当前没有进行中的签到，请先发起签到' });
  }
  // 签到窗口校验：截止后拒绝批量签到（**每天自动签到 v35 例外**：auto 场次不限时）
  if (!session.auto_generated && new Date() > new Date(session.deadline)) {
    await finalizeAbsent(session.id);
    return res.status(400).json({ error: '签到窗口已关闭' });
  }

  let targetStudents = [];
  if (mode === 'all') {
    targetStudents = (
      await pool.query(
        "SELECT id, name FROM students WHERE is_active = true AND status = '在读' AND class_id = $1 ORDER BY student_no",
        [classId]
      )
    ).rows;
  } else if (mode === 'column') {
    const ci = Number(columnIndex);
    if (!Number.isInteger(ci) || ci < 1 || ci > 20) {
      return res.status(400).json({ error: '列号无效' });
    }
    targetStudents = (
      await pool.query(
        `SELECT id, name FROM students
          WHERE is_active = true AND status = '在读' AND class_id = $1
            AND seat_col = $2 AND seat_row > 0
          ORDER BY seat_row`,
        [classId, ci]
      )
    ).rows;
  } else {
    return res.status(400).json({ error: 'mode 必须是 all 或 column' });
  }

  if (targetStudents.length === 0) {
    return res.status(400).json({
      error: mode === 'all' ? '该班级暂无在读学生' : `第 ${columnIndex} 列暂无在读学生（可能未排座）`,
    });
  }

  const method = checkInMethod || (mode === 'all' ? 'batch_all' : 'batch_column');
  let updated = 0;
  let skipped = 0;
  for (const st of targetStudents) {
    // 「全员到齐 / 按列签到」只补齐【尚未标记】的学生：
    //   · 已请假(leave)/已迟到(late)/已签到(present) 一律不动（旧实现会用 DO UPDATE 把请假覆盖成已签到）
    //   · 仅自动补写的缺勤(absent)允许被改为已签到/迟到（保持原有"缺勤可补"的语义）
    //   每天自动签到（v35）：不限时 → $5=true 时一律 present（不产生"迟到"）
    const { rowCount } = await pool.query(
      `INSERT INTO attendance_records (session_id, student_id, status, leave_reason, checkin_time, check_in_method, column_index)
       SELECT $1, $2,
              CASE WHEN $5::boolean OR now() <= deadline THEN 'present' ELSE 'late' END,
              NULL, now(), $3, $4
         FROM attendance_sessions
        WHERE id = $1
          AND NOT EXISTS (
            SELECT 1 FROM attendance_records r
             WHERE r.session_id = $1 AND r.student_id = $2 AND r.status <> 'absent'
          )
       ON CONFLICT (session_id, student_id) DO UPDATE
         SET status = EXCLUDED.status,
             checkin_time = EXCLUDED.checkin_time,
             check_in_method = EXCLUDED.check_in_method,
             column_index = EXCLUDED.column_index
         WHERE attendance_records.status = 'absent'`,
      [session.id, st.id, method, mode === 'column' ? Number(columnIndex) : null, session.auto_generated === true]
    );
    if (rowCount > 0) updated += 1;
    else skipped += 1;
  }
  await logOperation(req, mode === 'all' ? 'batch_all_checkin' : 'column_checkin', {
    sessionId: session.id,
    classId,
    count: targetStudents.length,
    updated,
    skipped,
    columnIndex: mode === 'column' ? Number(columnIndex) : null,
    method,
  });
  res.json({
    ok: true,
    updated,
    skipped,
    total: targetStudents.length,
    method,
    columnIndex: mode === 'column' ? Number(columnIndex) : null,
  });
}

// 将日期值格式化为 YYYY-MM-DD（PG DATE 经 node-postgres 解析为本地时区 Date）
function fmtDate(d) {
  if (!d) return null;
  if (d instanceof Date) {
    const y = d.getFullYear();
    const m = String(d.getMonth() + 1).padStart(2, '0');
    const day = String(d.getDate()).padStart(2, '0');
    return `${y}-${m}-${day}`;
  }
  const s = String(d);
  return /^\d{4}-\d{2}-\d{2}/.test(s) ? s.slice(0, 10) : s;
}


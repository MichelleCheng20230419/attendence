// 注意：旧实现里的 getActiveSession()（取全局 id 最大的 active 场次）已删除。
// "当前场次"必须按班级解析 → 一律走 activeSessionFor(classId)（见文件后部的「班级隔离统一解析层」）。
// 全局取最大 id 会让 A 班的签到台看到 B 班的场次，这正是隔离问题反复出现的根因。

// 为该场次中“尚无记录”的学生补写 absent（缺勤）记录（第五步）
// 注意：只处理 active 且状态为“在读”的学生（休学/转学/退学不参与）
// 当天已登记「全天请假」（student_day_leaves，批量请假）的学生 → 记 leave 而不是 absent
// 班级范围：只给【本场次范围内的班级】补缺勤（全班场次=全校；某班专属计划场次=该班），
//          不再给别的班写缺勤（这正是"教师看到本班全体缺勤"的数据来源）
async function finalizeAbsent(sessionId) {
  // 场次归属（唯一真源）：class_id IS NULL → 全校；否则只覆盖该班
  const scope = await sessionScopeOf(sessionId);
  const schoolWide = !scope || scope.schoolWide;
  const classIds = scope && scope.classId ? [scope.classId] : [];
  await pool.query(
    `INSERT INTO attendance_records (session_id, student_id, status, leave_reason, checkin_time, check_in_method)
     SELECT $1, s.id,
            CASE WHEN dl.student_id IS NULL THEN 'absent' ELSE 'leave' END,
            dl.reason,
            now(),
            CASE WHEN dl.student_id IS NULL THEN 'manual' ELSE $2 END
       FROM students s
       LEFT JOIN student_day_leaves dl
              ON dl.student_id = s.id
             AND dl.leave_date = (SELECT (ss.start_time)::date FROM attendance_sessions ss WHERE ss.id = $1)
      WHERE s.is_active = true
        AND s.status = '在读'
        AND ($3::boolean OR s.class_id = ANY($4::int[]))
        AND NOT EXISTS (
        SELECT 1 FROM attendance_records r
         WHERE r.session_id = $1 AND r.student_id = s.id
      )`,
    [sessionId, DAY_LEAVE_METHOD, schoolWide, classIds]
  );
}

// ------------------------------------------------------------
// 当天「全天请假」（签到操作台 → 📋 批量请假）
//   student_day_leaves：一个学生一天一条登记（病假 sick / 事假 personal / 公假 official）
//   落到场次：status=leave + leave_reason=事由 + check_in_method='batch_leave'
//   规则：无记录 / absent / 已有 leave → 写或覆盖为 leave；
//         present / late（已签到、迟到）→ 不动（避免抹掉真实签名），返回给前端提示
// ------------------------------------------------------------
// 把某天的全天请假登记同步到一个场次（场次日期由该场次的 start_time 决定）
// 班级范围：只同步到【本场次范围内的班级】（全校场次=全员；某班专属计划场次=该班），
//          避免把 A 班的请假写进 B 班的计划场次（否则会污染 B 班场次、并让 A 班老师"看到" B 班场次）
// 返回 { inserted, updated, skipped: [studentId...] }
async function applyDayLeaves(sessionId) {
  if (!sessionId) return { inserted: 0, updated: 0, skipped: [] };
  // 场次归属（唯一真源）：全校场次对所有班生效；班级专属场次只对该班生效
  const scope = await sessionScopeOf(sessionId);
  const schoolWide = !scope || scope.schoolWide;
  const classIds = scope && scope.classId ? [scope.classId] : [];
  // 每天自动签到（v35）：该场次的 present 是"默认全员已签到"（或整场保存写入的），
  //   不是学生本人一次一次点出来的签名 → 全天请假**应当覆盖它**（否则请了假还显示已签到）。
  //   老场次保持原样：present/late 一律不动（避免抹掉真实签名）。
  const isAuto = !!(scope && scope.autoGenerated);
  const upd = await pool.query(
    `UPDATE attendance_records r
        SET status = 'leave',
            leave_reason = dl.reason,
            check_in_method = $2,
            checkin_time = COALESCE(r.checkin_time, now())
       FROM student_day_leaves dl
       JOIN students st ON st.id = dl.student_id
      WHERE r.session_id = $1
        AND dl.student_id = r.student_id
        AND dl.leave_date = (SELECT (ss.start_time)::date FROM attendance_sessions ss WHERE ss.id = $1)
        AND (r.status IN ('absent', 'leave') OR ($5::boolean AND r.status = 'present'))
        AND ($3::boolean OR st.class_id = ANY($4::int[]))`,
    [sessionId, DAY_LEAVE_METHOD, schoolWide, classIds, isAuto]
  );
  const ins = await pool.query(
    `INSERT INTO attendance_records (session_id, student_id, status, leave_reason, checkin_time, check_in_method)
     SELECT $1, dl.student_id, 'leave', dl.reason, now(), $2
       FROM student_day_leaves dl
       JOIN students s ON s.id = dl.student_id AND s.is_active = true AND s.status = '在读'
      WHERE dl.leave_date = (SELECT (ss.start_time)::date FROM attendance_sessions ss WHERE ss.id = $1)
        AND ($3::boolean OR s.class_id = ANY($4::int[]))
        AND NOT EXISTS (SELECT 1 FROM attendance_records r WHERE r.session_id = $1 AND r.student_id = dl.student_id)`,
    [sessionId, DAY_LEAVE_METHOD, schoolWide, classIds]
  );
  const skip = await pool.query(
    `SELECT r.student_id
       FROM attendance_records r
       JOIN student_day_leaves dl ON dl.student_id = r.student_id
      WHERE r.session_id = $1
        AND dl.leave_date = (SELECT (ss.start_time)::date FROM attendance_sessions ss WHERE ss.id = $1)
        AND r.status IN ('present', 'late')`,
    [sessionId]
  );
  return { inserted: ins.rowCount, updated: upd.rowCount, skipped: skip.rows.map((x) => x.student_id) };
}

// 取消某天的全天请假：撤销"批量请假"写入的场次记录
//   进行中场次 → 删除记录（学生回到"待签"）；已结束场次 → 还原为缺勤
async function revertDayLeaveRecords(studentIds, dateStr) {
  const ids = [...new Set((studentIds || []).map(Number).filter((x) => Number.isInteger(x) && x > 0))];
  if (!ids.length) return { removed: 0, reverted: 0 };
  const sessions = (await pool.query(
    'SELECT id, status FROM attendance_sessions WHERE (start_time)::date = $1::date',
    [dateStr]
  )).rows;
  const activeIds = sessions.filter((s) => s.status === 'active').map((s) => s.id);
  const closedIds = sessions.filter((s) => s.status !== 'active').map((s) => s.id);
  let removed = 0, reverted = 0;
  if (activeIds.length) {
    const r = await pool.query(
      `DELETE FROM attendance_records
        WHERE session_id = ANY($1::int[]) AND student_id = ANY($2::int[])
          AND status = 'leave' AND check_in_method = $3`,
      [activeIds, ids, DAY_LEAVE_METHOD]
    );
    removed = r.rowCount;
  }
  if (closedIds.length) {
    const r = await pool.query(
      `UPDATE attendance_records
          SET status = 'absent', leave_reason = NULL, check_in_method = 'manual'
        WHERE session_id = ANY($1::int[]) AND student_id = ANY($2::int[])
          AND status = 'leave' AND check_in_method = $3`,
      [closedIds, ids, DAY_LEAVE_METHOD]
    );
    reverted = r.rowCount;
  }
  return { removed, reverted };
}


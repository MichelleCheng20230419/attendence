// GET /api/students —— 获取学生列表（含班级/状态信息）
// 参数：status?（如 在读/休学，缺省=全部 active）；classId?（按班级过滤）
// ------------------------------------------------------------
router.get('/students', async (req, res, next) => {
  try {
    const status = req.query.status ? String(req.query.status).trim() : null;
    let classId = req.query.classId ? Number(req.query.classId) : null;
    // 权限（角色菜单矩阵）：学生管理仅管理员/教师可见；
    // 班长与学生只能读取【本班】名单（未指定班级时自动限定为本班，指定他班 → 403）
    const role = req.session.user.role;
    if (role === 'monitor' || role === 'student') {
      const me = await pool.query('SELECT class_id FROM users WHERE id = $1', [req.session.user.id]);
      const myClassId = (me.rows[0] && me.rows[0].class_id) || null;
      if (!myClassId) return res.json({ students: [] });
      if (Number.isInteger(classId) && classId !== myClassId) {
        return res.status(403).json({ error: '无权限：只能查看本班学生' });
      }
      classId = myClassId;
    }
    const p = [];
    let where = 'WHERE s.is_active = true';
    if (status) { p.push(status); where += ` AND s.status = $${p.length}`; }
    if (classId && Number.isInteger(classId)) { p.push(classId); where += ` AND s.class_id = $${p.length}`; }
    const { rows } = await pool.query(
      `SELECT s.id, s.student_no, s.name, s.class_id, s.status, c.class_name,
              s.gender, s.birth_date, s.id_card, s.nationality, s.political_status,
              s.phone, s.address, s.enrollment_date, s.graduation_school,
              s.emergency_contact, s.emergency_phone, s.remarks,
              s.seat_row, s.seat_col
         FROM students s
         LEFT JOIN classes c ON c.id = s.class_id
         ${where}
        ORDER BY s.student_no`,
      p
    );
    res.json({
      students: rows.map((r) => ({
        id: r.id,
        studentNo: r.student_no,
        name: r.name,
        classId: r.class_id,
        className: r.class_name || null,
        status: r.status || '在读',
        gender: r.gender,
        birthDate: fmtDate(r.birth_date),
        idCard: r.id_card,
        nationality: r.nationality,
        politicalStatus: r.political_status,
        phone: r.phone,
        address: r.address,
        enrollmentDate: fmtDate(r.enrollment_date),
        graduationSchool: r.graduation_school,
        emergencyContact: r.emergency_contact,
        emergencyPhone: r.emergency_phone,
        remarks: r.remarks,
        seatRow: r.seat_row || 0,
        seatCol: r.seat_col || 0,
      })),
    });
  } catch (err) {
    next(err);
  }
});


// POST /api/attendance/leave/batch —— 批量登记/取消「当天全天请假」
// body: { date?: 'YYYY-MM-DD'(默认今天，且只允许今天), items: [{studentId, reason}], cancels: [studentId] }
//   语义：items = 要登记（或改事由）的学生；cancels = 要取消请假的学生（回到待签/缺勤）
//   副作用：同步到**当天所有场次**的记录（进行中 + 已结束的历史场次）；
//          之后新建的场次（手动发起 / 计划触发）会自动带上这些请假
// ------------------------------------------------------------
router.post('/attendance/leave/batch', async (req, res, next) => {
  try {
    const me = req.session.user;
    if (me.role !== 'monitor' && me.role !== 'teacher' && me.role !== 'admin') {
      return res.status(403).json({ error: '无权限：仅教师/班主任/管理员/班长可登记请假' });
    }
    const today = (await pool.query("SELECT to_char(now(), 'YYYY-MM-DD') AS today")).rows[0].today;
    const date = String((req.body && req.body.date) || today);
    if (!isValidDateStr(date)) {
      return res.status(400).json({ error: '日期格式应为 YYYY-MM-DD（且需为真实日期）' });
    }
    if (date !== today) {
      return res.status(400).json({ error: `只能登记当天的请假（今天是 ${today}）` });
    }

    const rawItems = Array.isArray(req.body && req.body.items) ? req.body.items : [];
    const rawCancels = Array.isArray(req.body && req.body.cancels) ? req.body.cancels : [];
    const wanted = new Map();
    for (const it of rawItems) {
      const sid = Number(it && it.studentId);
      const reason = String((it && it.reason) || '');
      if (!Number.isInteger(sid) || sid <= 0) {
        return res.status(400).json({ error: '请假条目缺少有效的 studentId' });
      }
      if (!LEAVE_CODES.has(reason)) {
        return res.status(400).json({ error: '请假类型无效（sick=病假 / personal=事假）' });
      }
      wanted.set(sid, reason);
    }
    const cancels = [...new Set(rawCancels.map(Number).filter((x) => Number.isInteger(x) && x > 0))];
    // 同一学生既在 cancels 又在 items 时，以 items（登记）为准
    const cancelIds = cancels.filter((id) => !wanted.has(id));
    const ids = [...new Set([...wanted.keys(), ...cancelIds])];
    if (ids.length === 0) {
      return res.status(400).json({ error: '请先勾选学生（或取消已有请假）' });
    }

    // 范围校验：与学生列表同一口径（班长/教师只允许所带班级；管理员按 ?classId= > 绑定班级 > 不限）
    const viewer = await viewerScope(me, req.body && req.body.classId);
    if (viewer.error) return res.status(viewer.status || 400).json({ error: viewer.error });
    const meRow = await pool.query('SELECT class_id FROM users WHERE id = $1', [me.id]);
    const userClassId = (meRow.rows[0] && meRow.rows[0].class_id) || null;
    const scopeParams = [ids];
    let scopeCond = '';
    if (!viewer.schoolWideView) { scopeParams.push(viewer.classIds); scopeCond = ` AND class_id = ANY($${scopeParams.length}::int[])`; }
    const allowed = (await pool.query(
      `SELECT id FROM students WHERE id = ANY($1::int[]) AND is_active = true AND status = '在读'${scopeCond}`,
      scopeParams
    )).rows.map((r) => r.id);
    const invalid = ids.filter((id) => !allowed.includes(id));
    if (invalid.length) {
      return res.status(403).json({ error: '无权限：包含不在你管理范围内的学生', invalidStudentIds: invalid });
    }

    // 1) 写/改/删当天登记（唯一键 (student_id, leave_date) → 重复提交是幂等的"改事由"）
    const client = await pool.connect();
    try {
      await client.query('BEGIN');
      for (const [studentId, reason] of wanted) {
        await client.query(
          `INSERT INTO student_day_leaves (student_id, leave_date, reason, created_by, created_by_name)
           VALUES ($1, $2::date, $3, $4, $5)
           ON CONFLICT (student_id, leave_date) DO UPDATE
              SET reason = EXCLUDED.reason, updated_at = now(),
                  created_by = EXCLUDED.created_by, created_by_name = EXCLUDED.created_by_name`,
          [studentId, date, reason, me.id, me.displayName || me.username]
        );
      }
      if (cancelIds.length) {
        await client.query(
          'DELETE FROM student_day_leaves WHERE leave_date = $1::date AND student_id = ANY($2::int[])',
          [date, cancelIds]
        );
      }
      await client.query('COMMIT');
    } catch (e) {
      await client.query('ROLLBACK');
      throw e;
    } finally {
      client.release();
    }

    // 2) 同步到当天【本账号可见】的已有场次（进行中 + 已结束；别班的班级专属场次不碰）
    const sessParams = [date];
    let sessCond = '';
    if (!viewer.schoolWideView) {
      sessParams.push(viewer.classIds);
      sessCond = ` AND (class_id IS NULL OR class_id = ANY($${sessParams.length}::int[]))`;
    }
    const sessions = (await pool.query(
      `SELECT id FROM attendance_sessions WHERE (start_time)::date = $1::date${sessCond} ORDER BY id`,
      sessParams
    )).rows;
    let inserted = 0, updated = 0;
    const skipped = new Set();
    for (const s of sessions) {
      const r = await applyDayLeaves(s.id);
      inserted += r.inserted;
      updated += r.updated;
      r.skipped.forEach((id) => skipped.add(id));
    }
    // 3) 取消请假：撤销这些学生当天由批量请假写入的记录
    const revert = await revertDayLeaveRecords(cancelIds, date);

    // 当天已登记人数：按同一班级范围统计
    const cntParams = [date];
    let cntCond = '';
    if (!viewer.schoolWideView) {
      cntParams.push(viewer.classIds);
      cntCond = ` AND dl.student_id IN (SELECT id FROM students WHERE class_id = ANY($${cntParams.length}::int[]))`;
    }
    const dayLeaveCount = (await pool.query(
      `SELECT count(*)::int n FROM student_day_leaves dl WHERE dl.leave_date = $1::date${cntCond}`,
      cntParams
    )).rows[0].n;
    const active = await activeSessionFor(viewer.displayClassId || userClassId);
    await logOperation(req, 'batch_leave', {
      date,
      marked: wanted.size,
      cancelled: cancelIds.length,
      sessionIds: sessions.map((s) => s.id),
      updatedRecords: updated,
      insertedRecords: inserted,
      skippedSignedIn: [...skipped],
      revertedRecords: revert.removed + revert.reverted,
    });
    res.json({
      date,
      marked: wanted.size,
      cancelled: cancelIds.length,
      dayLeaveCount,
      sessionCount: sessions.length,
      updatedRecords: updated,
      insertedRecords: inserted,
      skippedSignedIn: [...skipped],      // 已签到/迟到 → 未被改动（前端提示）
      revertedRecords: revert.removed + revert.reverted,
      currentSessionId: active ? active.id : null,
    });
  } catch (err) { next(err); }
});


const STUDENT_PROFILE_COLS = [
  ['gender', 'gender'],
  ['birthDate', 'birth_date'],
  ['idCard', 'id_card'],
  ['nationality', 'nationality'],
  ['politicalStatus', 'political_status'],
  ['phone', 'phone'],
  ['address', 'address'],
  ['enrollmentDate', 'enrollment_date'],
  ['graduationSchool', 'graduation_school'],
  ['emergencyContact', 'emergency_contact'],
  ['emergencyPhone', 'emergency_phone'],
  ['remarks', 'remarks'],
];

// 将档案字段写入 students（只更新传入的非空字段）
async function applyStudentProfile(studentId, body) {
  const sets = [];
  const params = [studentId];
  for (const [key, col] of STUDENT_PROFILE_COLS) {
    if (body[key] !== undefined && body[key] !== null) {
      const v = String(body[key]).trim();
      sets.push(`${col} = $${params.length + 1}`);
      params.push(v === '' ? null : v);
    }
  }
  if (sets.length > 0) {
    await pool.query(
      `UPDATE students SET ${sets.join(', ')} WHERE id = $1`,
      params
    );
  }
}


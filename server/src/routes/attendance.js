// PUT /api/students/:id —— 编辑学生（姓名/班级；学号不可修改）
// body: { name, classId }
// ------------------------------------------------------------
router.put('/students/:id', async (req, res, next) => {
  try {
    const id = Number(req.params.id);
    if (!Number.isInteger(id)) {
      return res.status(400).json({ error: '无效的学生ID' });
    }
    const name = String(req.body.name ?? '').trim();
    const classId = Number(req.body.classId);
    if (!name) {
      return res.status(400).json({ error: '姓名不能为空' });
    }
    if (!Number.isInteger(classId)) {
      return res.status(400).json({ error: '必须选择班级' });
    }
    const cls = await pool.query('SELECT id FROM classes WHERE id = $1', [classId]);
    if (cls.rowCount === 0) {
      return res.status(400).json({ error: '所选班级不存在' });
    }
    const r = await pool.query(
      'UPDATE students SET name = $2, class_id = $3 WHERE id = $1 AND is_active = true',
      [id, name, classId]
    );
    if (r.rowCount === 0) {
      return res.status(404).json({ error: '学生不存在或已删除' });
    }
    await applyStudentProfile(id, req.body);
    const { rows } = await pool.query(
      `SELECT s.id, s.student_no, s.name, s.class_id, c.class_name
         FROM students s
         LEFT JOIN classes c ON c.id = s.class_id
        WHERE s.id = $1`,
      [id]
    );
    const st = rows[0];
    res.json({
      student: {
        id: st.id,
        studentNo: st.student_no,
        name: st.name,
        classId: st.class_id,
        className: st.class_name || null,
      },
    });
  } catch (err) {
    next(err);
  }
});


// POST /api/attendance/records —— 手动补签（修改某学生某场次的状态）
// body: { sessionId, studentId, status: present|leave|late|absent, leaveReason? }
// 权限（班级隔离）：必须同时满足
//   ① 该场次对本账号可见（别班的班级专属场次 → 403；用 assertSessionVisible 统一判定）
//   ② 该学生在本账号班级范围内（避免"借场次改别班学生"）
router.post('/attendance/records', async (req, res, next) => {
  const { sessionId, studentId, status, leaveReason } = req.body;
  try {
    const sid = Number(sessionId);
    const stuId = Number(studentId);
    if (!Number.isInteger(sid) || !Number.isInteger(stuId)) {
      return res.status(400).json({ error: 'sessionId 和 studentId 必须是数字' });
    }
    const VALID = ['present', 'leave', 'late', 'absent'];
    if (!VALID.includes(status)) {
      return res.status(400).json({ error: 'status 必须是 present/leave/late/absent' });
    }
    const guard = await assertSessionVisible(req.session.user, sid, { classId: req.body.classId });
    if (guard.error) return res.status(guard.status || 403).json({ error: guard.error });
    const stu = await pool.query(
      "SELECT id, class_id FROM students WHERE id = $1 AND is_active = true AND status = '在读'",
      [stuId]
    );
    if (stu.rowCount === 0) {
      return res.status(404).json({ error: '学生不存在' });
    }
    const stuClassId = stu.rows[0].class_id || null;
    // 学生必须属于"该场次范围内"的班级（全校场次=任意班；班级专属场次=该班）
    if (!guard.session.schoolWide && stuClassId !== guard.session.classId) {
      return res.status(403).json({ error: '无权限：该学生不属于本场次对应的班级' });
    }
    // 学生还必须在本账号可见范围内（教师/班长只限所带班级；管理员按 ?classId=/绑定班级）
    if (!guard.viewer.schoolWideView && (!stuClassId || !guard.viewer.classIds.includes(stuClassId))) {
      return res.status(403).json({ error: '无权限：该学生不属于你所带的班级' });
    }
    if (status === 'leave' && !['sick', 'personal', 'official'].includes(leaveReason)) {
      return res.status(400).json({ error: '请假必须提供有效事由（sick/personal/official）' });
    }
    const { rows } = await pool.query(
      `INSERT INTO attendance_records (session_id, student_id, status, leave_reason, checkin_time)
       VALUES ($1, $2, $3, $4, now())
       ON CONFLICT (session_id, student_id) DO UPDATE
          SET status = EXCLUDED.status,
              leave_reason = EXCLUDED.leave_reason,
              checkin_time = now()
       RETURNING id, status, leave_reason, checkin_time`,
      [sid, stuId, status, status === 'leave' ? leaveReason : null]
    );
    res.json({ record: mapRecord(rows[0]) });
  } catch (err) {
    next(err);
  }
});


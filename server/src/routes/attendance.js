// DELETE /api/attendance/sessions/:id —— 删除【已结束】的签到场次（仅管理员）
//   用途：删除错误/多余的已结束签到（如计划抖动产生的场次）
//   权限：仅管理员（班主任/任课老师/班长一律 403）
//   约束：只允许删除非进行中的场次（进行中请先结束或等截止），进行中 → 409
//   级联：attendance_records.session_id → ON DELETE CASCADE（签到记录一并删除）；
//         attendance_plans.session_id → ON DELETE SET NULL（计划保留，可再次补签）
//   返回：被删除的场次信息 + 同时删除的记录数
// ------------------------------------------------------------
router.delete('/attendance/sessions/:id', async (req, res, next) => {
  try {
    if (req.session.user.role !== 'admin') {
      return res.status(403).json({ error: '无权限：仅管理员可删除已结束的签到' });
    }
    const id = Number(req.params.id);
    if (!Number.isInteger(id) || id <= 0) {
      return res.status(400).json({ error: '无效的场次ID' });
    }
    const s = await pool.query(
      `SELECT id, start_time, deadline, status, start_source, created_by_name,
              (SELECT count(*)::int FROM attendance_records r WHERE r.session_id = s.id) AS records
         FROM attendance_sessions s WHERE id = $1`,
      [id]
    );
    if (s.rowCount === 0) return res.status(404).json({ error: '场次不存在' });
    const row = s.rows[0];
    const stillRunning = row.status === 'active' && new Date(row.deadline) > new Date();
    if (stillRunning) {
      return res.status(409).json({
        error: '该签到正在进行中，不能删除（请先结束该场次或等截止后再删）',
        canClose: true,
        closeUrl: `/api/attendance/sessions/${id}/close`,
      });
    }
    // 事务：先收尾计划（避免"删了又被计划重建"），再删记录、最后删场次
    const client = await pool.connect();
    let records = 0;
    let planEnded = 0;
    try {
      await client.query('BEGIN');
      // 计划侧收尾：本场次对应的「进行中」计划一并置为已结束。
      //   否则 repairActivePlans() 在计划窗口内（session 缺失但未过截止）会**立刻重建场次**
      //   → 管理员刚删掉的签到几秒后又出现（实测泄漏：驱动删场次后 0.3 秒被重建）。
      //   计划行保留（列表里显示"已结束"），只是不再自动重建；需要再签请在计划管理里重新发起。
      const pl = await client.query(
        `UPDATE attendance_plans SET status = 'ended' WHERE session_id = $1 AND status = 'active'`,
        [id]
      );
      planEnded = pl.rowCount;
      const delRec = await client.query('DELETE FROM attendance_records WHERE session_id = $1', [id]);
      records = delRec.rowCount;
      await client.query('DELETE FROM attendance_sessions WHERE id = $1', [id]);
      await client.query('COMMIT');
    } catch (e) {
      await client.query('ROLLBACK');
      throw e;
    } finally {
      client.release();
    }
    await logOperation(req, 'session_delete', {
      sessionId: id,
      startTime: row.start_time,
      status: row.status,
      startSource: row.start_source,
      recordsDeleted: records,
      planEnded,
    });
    res.json({
      deleted: true,
      sessionId: id,
      recordsDeleted: records,
      planEnded,          // 被一并收尾的"进行中"计划数（>0 时前端提示"不会自动重建"）
      startTime: row.start_time,
      status: row.status,
    });
  } catch (err) {
    next(err);
  }
});


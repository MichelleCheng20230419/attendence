// POST /api/students/seats —— 保存座位布局（批量更新 seat_row/seat_col）
// body: { classId, seats: [{ studentId, row, col }], seatConfig?: { cols, mode } }
// row/col 为 0 表示清空座位；seatConfig 可选，保存班级布局配置
// 事务内校验学生属于该班级，防止越权写他人座位
// ------------------------------------------------------------
router.post('/students/seats', async (req, res, next) => {
  try {
    const classId = Number(req.body.classId);
    const seats = req.body.seats;
    if (!Number.isInteger(classId)) {
      return res.status(400).json({ error: '无效的班级ID' });
    }
    if (!Array.isArray(seats)) {
      return res.status(400).json({ error: '缺少座位数据' });
    }
    // 校验并规范化
    const norm = [];
    const seen = new Set();
    for (const s of seats) {
      const studentId = Number(s && s.studentId);
      const row = Number(s && s.row);
      const col = Number(s && s.col);
      if (!Number.isInteger(studentId) || seen.has(studentId)) continue;
      if (!Number.isInteger(row) || !Number.isInteger(col) || row < 0 || col < 0 || row > 99 || col > 99) {
        return res.status(400).json({ error: `座位坐标无效（学生 ${studentId}）：行/列须为 0-99 的整数` });
      }
      seen.add(studentId);
      norm.push([studentId, row, col]);
    }
    // 布局配置校验（可选）
    let seatConfig = null;
    if (req.body.seatConfig && typeof req.body.seatConfig === 'object') {
      const cfg = req.body.seatConfig;
      const rows = Number(cfg.rows);
      const cols = Number(cfg.cols);
      const mode = String(cfg.mode || '');
      const MODES = ['标准', '左对齐', '右对齐', '居中', '左右分列', '自定义'];
      if (!Number.isInteger(rows) || rows < 4 || rows > 10) {
        return res.status(400).json({ error: '行数须为 4-10 的整数' });
      }
      if (!Number.isInteger(cols) || cols < 4 || cols > 10) {
        return res.status(400).json({ error: '列数须为 4-10 的整数' });
      }
      if (!MODES.includes(mode)) {
        return res.status(400).json({ error: '布局模式无效' });
      }
      seatConfig = { rows, cols, mode };
    }

    const client = await pool.connect();
    try {
      await client.query('BEGIN');
      // 仅更新属于该班级的学生
      for (const [studentId, row, col] of norm) {
        await client.query(
          `UPDATE students SET seat_row = $2, seat_col = $3
            WHERE id = $1 AND class_id = $4 AND is_active = true`,
          [studentId, row, col, classId]
        );
      }
      // 保存班级布局配置（可选）
      if (seatConfig) {
        await client.query(
          'UPDATE classes SET seat_config = $2 WHERE id = $1',
          [classId, JSON.stringify(seatConfig)]
        );
      }
      await client.query('COMMIT');
    } catch (e) {
      await client.query('ROLLBACK');
      throw e;
    } finally {
      client.release();
    }
    res.json({ ok: true, updated: norm.length, seatConfig });
  } catch (err) {
    next(err);
  }
});

